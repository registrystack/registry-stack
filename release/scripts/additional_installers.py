#!/usr/bin/env python3
"""Generate self-contained transactional product installers."""

from __future__ import annotations

import argparse
import hashlib
import os
from pathlib import Path
import re
import shutil
import subprocess
import tempfile

import release_roster

ROOT = Path(__file__).resolve().parents[2]
DISCOVERY_TEMPLATE = Path(__file__).with_name("discovery-install-template.sh")
TITLES = {
    "breg-mcp": "BReg MCP",
    "breg-review": "BReg Review",
    "messaging": "Messaging",
    "discovery": "Discovery",
    "registry-render": "Render",
    "registry-manifest": "Manifest",
    "coordinator": "Coordinator",
}


def typst_pin() -> str:
    match = re.search(
        r'^pub const TYPST_PIN: &str = "([^"]+)";',
        (ROOT / "crates/registry-render/src/lib.rs").read_text(),
        re.MULTILINE,
    )
    if match is None:
        raise ValueError("Render Typst version pin is missing")
    return match[1]


def expected_binary_version(binary: str, version: str) -> str:
    expected = f"{binary} {version}"
    if binary == "registry-render":
        expected += f" (typst {typst_pin()})"
    return expected


def render(name: str, template: str) -> str:
    if name == "discovery":
        template = DISCOVERY_TEMPLATE.read_text()
    _, prefix, binaries = release_roster.ADDITIONAL_INSTALLERS[name]
    template = template.replace(
        "Install the Registry Casework runtime and the caseworkctl adopter tooling.",
        "Install " + " and ".join(binaries) + ".",
    ).replace("two binaries together", "selected binaries together")
    template = template.replace(
        "  caseworkctl init --help\n  caseworkctl check --help\n  casework --help",
        "\n".join(f"  {binary} --help" for binary in binaries),
    )
    template = template.replace(
        "binaries=(casework caseworkctl)", "binaries=(" + " ".join(binaries) + ")"
    )
    template = (
        template.replace("CASEWORK", prefix)
        .replace("Casework", TITLES[name])
        .replace("casework", name)
    )
    if name == "registry-manifest":
        # Manifest has no crypto dependency, so its macOS executable has no
        # FIPS library closure and is distributed as a plain binary.
        template = re.sub(
            r"# FIPS on macOS.*?\nfi\n",
            "macos_bundle=0\n",
            template,
            count=1,
            flags=re.DOTALL,
        )
        template = template.replace(
            'if [ "$os_label" = "linux" ] && ! env -i', "if ! env -i"
        )
    if name == "registry-render":
        template = template.replace(
            '"$binary ${version#v}"',
            '"$binary ${version#v} (typst ' + typst_pin() + ')"',
        )
    generated_from = (
        "# Generated by release/scripts/additional_installers.py."
        if name == "discovery"
        else "# Generated by release/scripts/additional_installers.py from the Casework installer."
    )
    return template.replace(
        "set -euo pipefail\n",
        f"set -euo pipefail\n\n{generated_from}\n",
        1,
    )


def require_regular_file(path: Path, label: str) -> None:
    if not path.is_file() or path.is_symlink():
        raise SystemExit(f"{label} must be a regular non-symlink file: {path}")


def smoke_numbered_installers(
    bundle: Path,
    scratch_root: Path,
    version: str,
    tag: str,
    specs: dict[str, tuple[str, str, tuple[str, ...]]],
) -> None:
    if not bundle.is_dir():
        raise SystemExit(f"candidate bundle root does not exist: {bundle}")
    if not scratch_root.is_dir():
        raise SystemExit(f"smoke scratch root does not exist: {scratch_root}")

    required: list[tuple[Path, str]] = []
    for name, (_, _, binaries) in specs.items():
        required.append((bundle / f"{name}-{tag}-install.sh", "numbered installer"))
        for binary in binaries:
            required.append(
                (bundle / f"{binary}-{tag}-linux-amd64", "candidate payload")
            )
    for path, label in required:
        if not path.exists():
            raise SystemExit(f"missing {label}: {path.name}")
        require_regular_file(path, label)

    with tempfile.TemporaryDirectory(
        prefix="additional-installer-smoke-", dir=scratch_root
    ) as temporary:
        smoke_root = Path(temporary)
        for name, (_, prefix, binaries) in specs.items():
            assets = smoke_root / name / "assets"
            install = smoke_root / name / "install"
            assets.mkdir(parents=True)
            checksums: list[str] = []
            for binary in binaries:
                filename = f"{binary}-{tag}-linux-amd64"
                source = bundle / filename
                destination = assets / filename
                shutil.copy2(source, destination)
                with destination.open("rb") as payload:
                    digest = hashlib.file_digest(payload, "sha256").hexdigest()
                checksums.append(f"{digest}  {filename}\n")
            (assets / "SHA256SUMS").write_text("".join(checksums))

            environment = os.environ.copy()
            environment.pop(f"{prefix}_VERSION", None)
            environment[f"{prefix}_ASSET_DIR"] = str(assets)
            environment[f"{prefix}_INSTALL_DIR"] = str(install)
            environment["TMPDIR"] = str(smoke_root)
            installer = bundle / f"{name}-{tag}-install.sh"
            installed = subprocess.run(
                ["bash", str(installer)],
                env=environment,
                capture_output=True,
                text=True,
            )
            if installed.returncode != 0:
                raise SystemExit(
                    f"{name} numbered installer smoke failed\n"
                    f"{installed.stdout}{installed.stderr}"
                )

            for binary in binaries:
                result = subprocess.run(
                    [str(install / binary), "--version"],
                    env={},
                    capture_output=True,
                    text=True,
                )
                if result.returncode != 0:
                    raise SystemExit(
                        f"installed {binary} --version failed with exit "
                        f"{result.returncode}: {result.stderr.strip()}"
                    )
                expected = expected_binary_version(binary, version)
                if result.stdout.rstrip("\n") != expected:
                    raise SystemExit(
                        f"{binary} reported an unexpected version: "
                        f"expected {expected!r}, got {result.stdout.rstrip()!r}"
                    )
    print(f"Smoked {len(specs)} numbered additional installers for {tag}.")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--write", action="store_true")
    mode.add_argument("--check", action="store_true")
    mode.add_argument("--package", type=Path)
    mode.add_argument("--smoke", type=Path)
    parser.add_argument("--version")
    parser.add_argument("--tag")
    parser.add_argument("--scratch-root", type=Path)
    parser.add_argument("--exclude-unit", action="append", default=[])
    args = parser.parse_args()
    if args.package is not None or args.smoke is not None:
        if not args.version or args.tag != f"v{args.version}":
            parser.error(
                "numbered packaging and smoke require matching --version and --tag"
            )
        specs = release_roster.additional_installers(
            release_roster.parse_version(args.version)
        )
    else:
        specs = release_roster.ADDITIONAL_INSTALLERS
    unknown_exclusions = sorted(set(args.exclude_unit) - {"discovery"})
    if unknown_exclusions:
        parser.error(f"unsupported excluded release unit: {unknown_exclusions[0]}")
    if "discovery" in args.exclude_unit:
        specs = {name: spec for name, spec in specs.items() if name != "discovery"}
    if args.package is not None:
        args.package.mkdir(parents=True, exist_ok=True)
    if args.smoke is not None:
        scratch_root = args.scratch_root or Path(
            os.environ.get("TMPDIR", tempfile.gettempdir())
        )
        smoke_numbered_installers(
            args.smoke, scratch_root, args.version, args.tag, specs
        )
        return
    if args.scratch_root is not None:
        parser.error("--scratch-root requires --smoke")
    template = (ROOT / "crates/registry-casework/install.sh").read_text()
    for name, (crate, _, _) in specs.items():
        rendered = render(name, template)
        path = ROOT / "crates" / crate / "install.sh"
        if args.write:
            path.write_text(rendered)
            path.chmod(0o755)
        elif not path.is_file() or path.read_text() != rendered:
            raise SystemExit(f"generated installer is stale: {path.relative_to(ROOT)}")
        if args.package is not None:
            if rendered.count('default_version=""') != 1:
                raise SystemExit("installer pinning template changed")
            pinned = rendered.replace(
                'default_version=""', f'default_version="{args.tag}"'
            )
            if name == "discovery":
                if (
                    pinned.count('release_namespace="discovery"') != 1
                    or pinned.count('numbered_platforms="linux-amd64"') != 1
                ):
                    raise SystemExit("Discovery release namespace template changed")
                pinned = pinned.replace(
                    'release_namespace="discovery"',
                    'release_namespace="stack"',
                    1,
                ).replace(
                    'numbered_platforms="linux-amd64"',
                    'numbered_platforms="all-native"',
                    1,
                )
            for filename in (f"{name}-{args.tag}-install.sh", f"{name}-install.sh"):
                output = args.package / filename
                if output.exists():
                    raise SystemExit(f"refusing to overwrite installer: {output.name}")
                output.write_text(pinned)
                output.chmod(0o755)


if __name__ == "__main__":
    main()
