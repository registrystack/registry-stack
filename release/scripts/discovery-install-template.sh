asset_name() {
	local stem="${1}-${version}-${os_label}-${arch_label}"
	if [[ "$os_label" == "macos" ]]; then
		printf '%s.tar.gz\n' "$stem"
	else
		printf '%s\n' "$stem"
	fi
}

download() {
	local src="$1"
	local dest="$2"
	if [[ -n "$asset_dir" ]]; then
		local name="${src##*/}"
		if [[ ! -f "$asset_dir/$name" ]]; then
			return 1
		fi
		cp "$asset_dir/$name" "$dest"
	else
		curl -fsSL "$src" -o "$dest" 2>/dev/null
	fi
}

if [[ -n "$asset_dir" ]]; then
	printf 'Installing verified local Registry Discovery %s assets for %s/%s...\n' \
		"$version" "$os_label" "$arch_label"
else
	printf 'Downloading Registry Discovery %s for %s/%s...\n' \
		"$version" "$os_label" "$arch_label"
fi

embedded_product_version=""
for binary in "${binaries[@]}"; do
	asset="$(asset_name "$binary")"
	if ! download "$base_url/$asset" "$tmpdir/$asset"; then
		printf 'Could not read the published %s %s binary for %s/%s.\n' \
			"$binary" "$version" "$os_label" "$arch_label" >&2
		printf 'Check the selected release at https://github.com/%s/releases/tag/%s\n' "$repo" "$release_tag_url" >&2
		exit 1
	fi
done
if ! download "$base_url/SHA256SUMS" "$tmpdir/SHA256SUMS"; then
	printf '%s\n' 'Could not read SHA256SUMS for checksum verification.' >&2
	exit 1
fi

verify_asset() {
	local name="$1"
	local expected_hash actual_hash
	expected_hash="$(awk -v asset="$name" '
		$2 == asset { value = $1; count++ }
		END { if (count != 1) exit 1; print value }
	' "$tmpdir/SHA256SUMS" || true)"
	if [[ ! "$expected_hash" =~ ^[0-9a-f]{64}$ ]]; then
		printf 'SHA256SUMS has no unique canonical entry for %s.\n' "$name" >&2
		exit 1
	fi
	actual_hash="$(sha256_file "$tmpdir/$name")"
	if [[ "$actual_hash" != "$expected_hash" ]]; then
		printf 'Checksum verification failed for %s.\n' "$name" >&2
		exit 1
	fi
}

for binary in "${binaries[@]}"; do
	verify_asset "$(asset_name "$binary")"
done
printf '%s\n' 'Integrity checks passed: both binaries matched SHA256SUMS.'

validate_macos_bundle() {
	local binary="$1"
	local stem="${binary}-${version}-${os_label}-${arch_label}"
	local require_libraries=1
	local archive
	archive="$tmpdir/$(asset_name "$binary")"
	if [[ "$binary" == "discovery" ]]; then
		require_libraries=0
	fi
	if ! tar -tzf "$archive" >"$tmpdir/$binary.members" ||
		! awk -v executable="$stem" -v require_libraries="$require_libraries" '
			{
				if (seen[$0]++) { bad = 1; exit }
				if ($0 == executable) { binaries++; next }
				if ($0 == "THIRD_PARTY_NOTICES") { notices++; next }
				if ($0 ~ /^libaws_lc_fips_[A-Za-z0-9_]+\.dylib$/) {
					libraries++; next
				}
				bad = 1; exit
			}
			END {
				exit (bad || binaries != 1 || notices != 1 ||
					(require_libraries ? libraries < 1 : libraries != 0))
			}
		' "$tmpdir/$binary.members"; then
		printf 'Refusing an invalid macOS bundle roster: %s\n' "${archive##*/}" >&2
		exit 1
	fi
	if ! tar -tvzf "$archive" >"$tmpdir/$binary.types" ||
		! awk '
			$NF == "THIRD_PARTY_NOTICES" {
				if ($1 != "-rw-r--r--") bad = 1
				next
			}
			$1 != "-rwxr-xr-x" { bad = 1 }
			END { exit bad }
		' "$tmpdir/$binary.types"; then
		printf 'Refusing non-regular files or unexpected modes in %s\n' \
			"${archive##*/}" >&2
		exit 1
	fi
}

