#!/usr/bin/env bash
set -euo pipefail

repo="registrystack/registry-stack"
binaries=(discovery discoveryctl)
installer_name="discovery"
product_name="Registry Discovery"
version_env_name="DISCOVERY_VERSION"
bootstrap_tmp_prefix="discovery-bootstrap"
# Candidate packaging replaces this empty value with the product asset marker.
default_version=""
# The source and independent product installer use discovery/vX.Y.Z. Stack
# candidate packaging explicitly replaces this value with its release namespace.
release_namespace="discovery"
numbered_platforms="linux-amd64"
script_name="${BASH_SOURCE[0]:-}"
script_name="${script_name##*/}"
filename_version=""
if [[ "$script_name" =~ ^discovery-(v(0|[1-9][0-9]*)\.(0|[1-9][0-9]*)\.(0|[1-9][0-9]*)(-nightly\.[0-9]{8}\.[0-9a-f]{40})?)-install\.sh$ ]]; then
	filename_version="${BASH_REMATCH[1]}"
fi
if [[ -n "$default_version" && -n "$filename_version" && "$default_version" != "$filename_version" ]]; then
	printf 'Refusing an installer whose embedded release does not match its filename.\n' >&2
	exit 1
fi
default_version="${default_version:-$filename_version}"
install_dir="${DISCOVERY_INSTALL_DIR:-$HOME/.local/bin}"
asset_dir="${DISCOVERY_ASSET_DIR:-}"
version_override="${DISCOVERY_VERSION:-}"
version="${version_override:-$default_version}"
if [[ -n "$default_version" && -n "$version_override" && "$version_override" != "$default_version" ]]; then
	printf '%s\n' 'Refusing a version override that does not match the released installer asset.' >&2
	exit 1
fi

usage() {
	cat <<EOF
Install the Registry Discovery runtime and discoveryctl.

Usage:
  discovery-install.sh --version vMAJOR.MINOR.PATCH

Nightly selection:
  --channel nightly  Install the latest successfully published Stack nightly.
  --build <tag>      Install one immutable vX.Y.Z-nightly.YYYYMMDD.SHA build.

A published installer is already pinned to its release. The source
installer requires --version or DISCOVERY_VERSION for an independent numbered
release. It never infers that version from the latest Registry Stack release.

The installer verifies both binaries against SHA256SUMS, starts them to verify
their embedded product version, and switches the pair through one toolset
pointer. It does not verify release authenticity. For a higher-assurance
installation, verify the release first, then rerun with DISCOVERY_ASSET_DIR set
to that verified directory.

Environment:
  DISCOVERY_VERSION      Registry Discovery asset marker, vMAJOR.MINOR.PATCH.
  DISCOVERY_INSTALL_DIR  Install directory. Defaults to ~/.local/bin.
  DISCOVERY_ASSET_DIR    Read already-downloaded selected release assets from
                         this directory instead of downloading them.
EOF
	if [[ "$release_namespace/$numbered_platforms" == "stack/all-native" ]]; then
		printf '%s\n' 'This Stack installer supports Linux amd64, Linux arm64, and macOS arm64.'
	else
		printf '%s\n' 'Independent numbered Discovery releases support Linux amd64.'
	fi
}

need() {
	if ! command -v "$1" >/dev/null 2>&1; then
		printf "Registry Discovery installer needs '%s'.\n" "$1" >&2
		exit 1
	fi
}

# BEGIN generated release channel resolver
# Generated by release/scripts/render-installer-channel.py. Do not edit by hand.
channel=""
build=""
requested_version=""
while [ "$#" -gt 0 ]; do
	case "$1" in
	--version)
		[ "$#" -ge 2 ] || {
			echo "--version needs vMAJOR.MINOR.PATCH." >&2
			exit 2
		}
		[ -z "$requested_version" ] || {
			echo "--version may be supplied only once." >&2
			exit 2
		}
		requested_version="$2"
		shift 2
		;;
	--channel)
		[ "$#" -ge 2 ] || {
			echo "--channel needs a value." >&2
			exit 2
		}
		[ -z "$channel" ] || {
			echo "--channel may be supplied only once." >&2
			exit 2
		}
		channel="$2"
		shift 2
		;;
	--build)
		[ "$#" -ge 2 ] || {
			echo "--build needs an immutable nightly tag." >&2
			exit 2
		}
		[ -z "$build" ] || {
			echo "--build may be supplied only once." >&2
			exit 2
		}
		build="$2"
		shift 2
		;;
	--help | -h)
		usage
		exit 0
		;;
	*)
		printf 'Unknown option: %s\n' "$1" >&2
		usage >&2
		exit 2
		;;
	esac
done
if [ -n "$channel" ] && [ "$channel" != "nightly" ]; then
	printf 'Unknown release channel: %s. Supported channel: nightly.\n' "$channel" >&2
	exit 2
fi
selection_count=0
for selection in "$requested_version" "$channel" "$build"; do
	if [ -n "$selection" ]; then
		selection_count=$((selection_count + 1))
	fi
done
if [ "$selection_count" -gt 1 ]; then
	echo "--version, --channel, and --build are mutually exclusive." >&2
	exit 2
fi
if [ -n "$default_version" ] && { [ -n "$requested_version" ] || [ -n "$channel" ] || [ -n "$build" ]; }; then
	if [ -n "$requested_version" ]; then
		echo "Refusing a version override that does not match the released installer asset." >&2
		exit 1
	fi
	echo "This published installer is already pinned to $default_version; --channel and --build are not accepted." >&2
	exit 2
fi
if [ -n "$version_override" ] && { [ -n "$channel" ] || [ -n "$build" ]; }; then
	echo "$version_env_name cannot be combined with --channel or --build." >&2
	exit 2
fi
if [ -n "$requested_version" ] && [ -n "$version_override" ] && [ "$requested_version" != "$version_override" ]; then
	echo "Refusing conflicting --version and $version_env_name selections." >&2
	exit 1
fi
if [ -n "$requested_version" ]; then
	version="$requested_version"
fi

sha256_file() {
	local path="$1"
	local result
	if command -v shasum >/dev/null 2>&1; then
		result="$(shasum -a 256 "$path")"
	elif command -v sha256sum >/dev/null 2>&1; then
		result="$(sha256sum "$path")"
	else
		echo "$product_name installer needs 'shasum' or 'sha256sum' for checksum verification." >&2
		exit 1
	fi
	printf '%s\n' "${result%% *}"
}

manifest_value() {
	local key="$1"
	awk -v key="$key" '
		$0 ~ "^[[:space:]]*\\\"" key "\\\"[[:space:]]*:" {
			line = $0
			sub("^[[:space:]]*\\\"" key "\\\"[[:space:]]*:[[:space:]]*\\\"", "", line)
			sub("\\\"[[:space:]]*$", "", line)
			value = line
			count++
		}
		END { if (count != 1) exit 1; print value }
	' "$2"
}

manifest_asset_hash() {
	local wanted="$1"
	awk -v wanted="$wanted" '
		{
			name = $0
			if (name !~ /"name"[[:space:]]*:[[:space:]]*"/) next
			sub(/^.*"name"[[:space:]]*:[[:space:]]*"/, "", name)
			sub(/".*$/, "", name)
			if (name != wanted) next
			hash = $0
			if (hash !~ /"sha256"[[:space:]]*:[[:space:]]*"/) next
			sub(/^.*"sha256"[[:space:]]*:[[:space:]]*"/, "", hash)
			sub(/".*$/, "", hash)
			value = hash
			count++
		}
		END { if (count != 1) exit 1; print value }
	' "$2"
}

embedded_installer_version() {
	awk '
		/^default_version="v[0-9][0-9A-Za-z.-]*"$/ {
			line = $0
			sub(/^default_version="/, "", line)
			sub(/"$/, "", line)
			value = line
			count++
		}
		END { if (count != 1) exit 1; print value }
	' "$1"
}

run_unpinned_installer() {
	need curl
	local bootstrap_tmp manifest_url manifest normalized objects tag schema manifest_version
	local base_version source_sha created_at expected_base expected_installer installer_hash actual_hash
	bootstrap_tmp="$(mktemp -d 2>/dev/null || mktemp -d -t "$bootstrap_tmp_prefix")"
	trap 'rm -rf "$bootstrap_tmp"' EXIT
	trap 'exit 130' INT
	trap 'exit 143' TERM

	if [ -z "$channel" ] && [ -z "$build" ]; then
		echo "No $product_name version was selected. Pass --version vMAJOR.MINOR.PATCH or set $version_env_name." >&2
		exit 2
	fi

	if [ -n "$build" ]; then
		if [[ ! "$build" =~ ^v(0|[1-9][0-9]*)\.(0|[1-9][0-9]*)\.(0|[1-9][0-9]*)-nightly\.[0-9]{8}\.[0-9a-f]{40}$ ]]; then
			echo "--build requires vMAJOR.MINOR.PATCH-nightly.YYYYMMDD.FULL40CHARSHA." >&2
			exit 2
		fi
		manifest_url="https://github.com/${repo}/releases/download/${build}/nightly.json"
	else
		manifest_url="https://raw.githubusercontent.com/${repo}/nightly-channel/nightly.json"
	fi
	manifest="$bootstrap_tmp/nightly.json"
	if ! curl -fsSL "$manifest_url" -o "$manifest" 2>/dev/null; then
		echo "Could not download nightly metadata from $manifest_url" >&2
		exit 1
	fi
	# The producer validates the JSON before it advances the channel. Splitting
	# structural punctuation makes its scalar fields available to standard awk
	# without adding jq or Python as an installation prerequisite.
	normalized="$bootstrap_tmp/nightly.fields"
	tr '{}[],' '\n' <"$manifest" >"$normalized"
	objects="$bootstrap_tmp/nightly.objects"
	tr '\n}' ' \n' <"$manifest" >"$objects"
	schema="$(manifest_value schema_version "$normalized" || true)"
	tag="$(manifest_value tag "$normalized" || true)"
	manifest_version="$(manifest_value version "$normalized" || true)"
	base_version="$(manifest_value base_version "$normalized" || true)"
	source_sha="$(manifest_value source_sha "$normalized" || true)"
	created_at="$(manifest_value created_at "$normalized" || true)"
	if [ "$schema" != "registry-stack.nightly.v1" ] && [ "$schema" != "registry-stack.nightly.v2" ]; then
		echo "Refusing nightly metadata with a missing or unsupported schema_version." >&2
		exit 1
	fi
	if [[ ! "$tag" =~ ^v(0|[1-9][0-9]*)\.(0|[1-9][0-9]*)\.(0|[1-9][0-9]*)-nightly\.[0-9]{8}\.([0-9a-f]{40})$ ]]; then
		echo "Refusing nightly metadata with a non-canonical immutable tag." >&2
		exit 1
	fi
	if [ -n "$build" ] && [ "$tag" != "$build" ]; then
		printf 'Refusing nightly metadata for %s while installing %s.\n' "$tag" "$build" >&2
		exit 1
	fi
	expected_base="${tag#v}"
	expected_base="${expected_base%%-nightly.*}"
	if [ "$manifest_version" != "${tag#v}" ] || [ "$base_version" != "$expected_base" ] ||
		[ "$source_sha" != "${BASH_REMATCH[4]}" ] || [ -z "$created_at" ]; then
		echo "Refusing internally inconsistent nightly metadata." >&2
		exit 1
	fi
	expected_installer="${installer_name}-${tag}-install.sh"
	installer_hash="$(manifest_asset_hash "$expected_installer" "$objects" || true)"
	if [[ ! "$installer_hash" =~ ^[0-9a-f]{64}$ ]]; then
		printf 'Nightly metadata has no valid checksum for %s.\n' "$expected_installer" >&2
		exit 1
	fi
	if ! curl -fsSL "https://github.com/${repo}/releases/download/${tag}/${expected_installer}" \
		-o "$bootstrap_tmp/installer" 2>/dev/null; then
		printf 'Could not download immutable nightly installer %s.\n' "$expected_installer" >&2
		exit 1
	fi
	actual_hash="$(sha256_file "$bootstrap_tmp/installer")"
	if [ "$actual_hash" != "$installer_hash" ]; then
		printf 'Checksum verification failed for %s.\n' "$expected_installer" >&2
		exit 1
	fi
	if [ "$(embedded_installer_version "$bootstrap_tmp/installer" || true)" != "$tag" ]; then
		echo "The verified nightly installer does not embed the manifest tag." >&2
		exit 1
	fi
	printf 'Resolved nightly build %s from source %s.\n' "$tag" "$source_sha"
	printf 'Verified %s against nightly.json.\n' "$expected_installer"
	bash "$bootstrap_tmp/installer"
	exit $?
}

