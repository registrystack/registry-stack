fn credential_source() -> String {
    let steps = [
        ("create-license", "operator-token"),
        ("get-license", "operator-token"),
        ("patch-license", "operator-token"),
        ("reader-gets-license", "reader-token"),
        ("reject-missing-code-scheme", "operator-token"),
        ("reject-more-than-fifty-professions", "operator-token"),
        (
            "reject-professions-over-sixteen-kibibytes",
            "operator-token",
        ),
        ("list-only-committed-license", "operator-token"),
        ("create-water-authorization", "operator-token"),
        ("get-water-authorization", "operator-token"),
        ("reject-missing-unit-scheme", "operator-token"),
        ("reject-unknown-unit-scheme", "operator-token"),
        ("create-driving-entitlement", "operator-token"),
        ("reader-does-not-receive-driving-conditions", "reader-token"),
    ];
    let bindings: Vec<Value> = steps
        .into_iter()
        .map(|(step, token)| {
            json!({
                "journeyId": JOURNEY_ID,
                "stepId": step,
                "credential": {
                    "type": "bearer",
                    "tokenRef": format!("secret:file/{token}")
                }
            })
        })
        .collect();
    serde_norway::to_string(&json!({
        "apiVersion": "id.registrystack.org/formats/breg/schema-test-credentials/v1",
        "kind": "BRegSchemaTestCredentials",
        "bindings": bindings
    }))
    .expect("credentials serialize as YAML")
}

