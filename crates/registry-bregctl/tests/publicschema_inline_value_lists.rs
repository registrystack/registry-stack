    steps.push(operator_step(
        "get-license",
        "professional-license",
        json!({"type": "get", "recordCapture": "license"}),
        json!({"outcome": "success", "status": 200, "fields": {
            "professional-license-code": "LICENSE-1",
            "profession-code": first_professions
        }}),
    ));
