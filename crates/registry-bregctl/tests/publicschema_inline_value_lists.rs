#[test]
#[ignore = "requires the TLS PostgreSQL exports from products/breg/scripts/local-postgres-tls.sh"]
fn derived_publicschema_inline_value_lists_roundtrip_through_the_runtime() {
    let runtime = tokio::runtime::Builder::new_current_thread()
        .enable_all()
        .build()
        .expect("test runtime builds");
    let mut database = runtime.block_on(TestDatabase::create());
    let idp = runtime.block_on(MockIdp::start());
    let project = ProjectFixture::write(&database, &idp);

    let init = Command::new(env!("CARGO_BIN_EXE_bregctl"))
        .args([
            "--format",
            "json",
            "init",
            path(&project.project_root),
            "--from",
            "publicschema",
            "--selection",
            path(&project.selection),
        ])
        .output()
        .expect("bregctl init starts");
    assert_command_succeeded("bregctl init", &init);
    assert_generated_inline_value_schemas(&project.project_root);

    fs::write(
        project.project_root.join("tests/journeys.yaml"),
        journey_source(),
    )
    .expect("focused runtime journey writes");
    fs::write(&project.credentials, credential_source()).expect("credentials write");
    set_private(&project.credentials);

    let tested = Command::new(env!("CARGO_BIN_EXE_bregctl"))
        .args([
            "--format",
            "json",
            "test",
            path(&project.project_root),
            "--runtime-config",
            path(&project.runtime_config),
            "--credentials",
            path(&project.credentials),
            "--output",
            path(&project.receipt),
        ])
        .output()
        .expect("bregctl test starts");

    runtime.block_on(idp.stop());
    runtime.block_on(database.cleanup());

    assert_command_succeeded("bregctl test", &tested);
    let report: Value = serde_json::from_slice(&tested.stdout).expect("test report is JSON");
    assert_eq!(report["command"], "test");
    assert_eq!(report["successfulJourneyIds"], json!([JOURNEY_ID]));
    let receipt: Value = serde_json::from_slice(
        &fs::read(&project.receipt).expect("successful test writes its receipt"),
    )
    .expect("schema-test receipt is JSON");
    assert_eq!(receipt["kind"], "BRegSchemaTestReceipt");
    assert_eq!(receipt["successfulJourneyIds"], json!([JOURNEY_ID]));
}

fn assert_generated_inline_value_schemas(project: &Path) {
    let registry: Value = serde_norway::from_slice(
        &fs::read(project.join("registry.yaml")).expect("derived registry reads"),
    )
    .expect("derived registry is YAML");
    let records = registry["recordTypes"]
        .as_array()
        .expect("recordTypes is an array");

    let profession = field(records, "professional-license", "profession-code");
    assert_eq!(profession["type"], "structured");
    assert_eq!(profession["maximumBytes"], 16384);
    assert_list_wrapper(&profession["schema"]);
    let coded = &profession["schema"]["properties"]["values"]["items"];
    assert_eq!(coded["type"], "object");
    assert_eq!(coded["additionalProperties"], false);
    assert_eq!(coded["required"], json!(["code_value", "code_scheme"]));
    assert_eq!(coded["properties"]["code_value"]["maxLength"], 255);
    assert_eq!(coded["properties"]["code_scheme"]["maxLength"], 2048);
    assert_eq!(coded["properties"]["code_label"]["maxLength"], 255);
    assert_eq!(coded["properties"]["code_meaning"]["maxLength"], 2048);

    let quantity = field(
        records,
        "water-use-authorization",
        "authorized-water-quantity",
    );
    assert_eq!(quantity["type"], "structured");
    assert_eq!(quantity["maximumBytes"], 16384);
    assert_list_wrapper(&quantity["schema"]);
    let quantity = &quantity["schema"]["properties"]["values"]["items"];
    assert_eq!(quantity["type"], "object");
    assert_eq!(quantity["additionalProperties"], false);
    assert_eq!(
        quantity["required"],
        json!(["quantity_value", "unit_code", "unit_scheme"])
    );
    assert_eq!(quantity["properties"]["quantity_value"]["type"], "number");
    assert_eq!(quantity["properties"]["unit_code"]["maxLength"], 255);
    assert_eq!(
        quantity["properties"]["unit_scheme"]["enum"],
        json!(["ucum", "unece_rec20"])
    );

    let conditions = field(records, "driving-entitlement", "driving-condition-codes");
    assert_eq!(conditions["classification"], "restricted");
    assert_eq!(conditions["maximumBytes"], 16384);
    assert_list_wrapper(&conditions["schema"]);
}

fn field<'a>(records: &'a [Value], record: &str, field: &str) -> &'a Value {
    records
        .iter()
        .find(|candidate| candidate["id"] == record)
        .and_then(|record| record["fields"].as_array())
        .and_then(|fields| fields.iter().find(|candidate| candidate["id"] == field))
        .unwrap_or_else(|| panic!("derived registry carries {record}.{field}"))
}

fn assert_list_wrapper(schema: &Value) {
    assert_eq!(schema["type"], "object");
    assert_eq!(schema["additionalProperties"], false);
    assert_eq!(schema["required"], json!(["values"]));
    assert_eq!(schema["properties"]["values"]["type"], "array");
    assert_eq!(schema["properties"]["values"]["maxItems"], 50);
}

