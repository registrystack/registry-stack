#[test]
fn pre_timer_store_package_is_predecessor_only_and_unknown_features_refuse() {
    let root = native_minimal_package();
    let effective: Value = serde_json::from_slice(
        &fs::read(root.join("effective-model.json")).expect("effective model reads"),
    )
    .expect("effective model parses");
    let legacy_entities = serde_json::from_value::<BTreeMap<String, CompiledEntity>>(
        effective
            .get("recordTypes")
            .cloned()
            .expect("effective record types exist"),
    )
    .expect("legacy compiled entities remain readable");
    assert_eq!(
        load_package(&root, &local_package_context()).err(),
        Some(PackageError::EngineFeatureUpgradeRequired),
        "the current runtime never admits the legacy platform catalog"
    );

    let shared = verify_shared_package(&root).expect("legacy envelope verifies");
    let (manifest, loaded) =
        load_verified_closure(&root, &shared, false).expect("legacy closure verifies");
    validate_predecessor_engine_features(&manifest).expect("legacy feature set is supported");
    let mut partial = manifest.clone();
    partial
        .engine_features
        .remove(&PackageEngineFeature::CallerScopedIdempotency);
    assert_eq!(
        validate_predecessor_engine_features(&partial).err(),
        Some(PackageError::Derivation),
        "partial legacy feature sets remain refused"
    );
    validate_source_inventory(&manifest).expect("legacy source inventory remains readable");
    let mut falsely_current = manifest.clone();
    falsely_current.engine_features = current_engine_features();
    assert_eq!(
        rederive(&falsely_current, &loaded).err(),
        Some(PackageError::Derivation),
        "deserialize aliases do not make historical generated bytes current authority"
    );
    let effective: Value = parse_canonical(
        loaded
            .get("effective-model.json")
            .expect("legacy governed model is in the closure"),
    )
    .expect("legacy governed JSON is canonical");
    let effective_physical_names =
        serde_json::from_value::<PhysicalNameInventory>(effective["physicalNames"].clone())
            .expect("legacy effective physical names remain readable");
    let effective_queries =
        serde_json::from_value::<CompiledQueryInventory>(effective["queryInventory"].clone())
            .expect("legacy effective query inventory remains readable");
    let packaged_physical_names: PhysicalNameInventory =
        packaged_manifest_json(&manifest, &loaded, PackageFileRole::PhysicalNameInventory)
            .expect("legacy packaged physical names remain readable");
    let packaged_queries: CompiledQueryInventory =
        packaged_manifest_json(&manifest, &loaded, PackageFileRole::QueryInventory)
            .expect("legacy packaged query inventory remains readable");
    packaged_manifest_json::<CompiledRouteInventory>(
        &manifest,
        &loaded,
        PackageFileRole::RouteInventory,
    )
    .expect("legacy packaged route inventory remains readable");
    packaged_manifest_json::<CompiledAccessInventory>(
        &manifest,
        &loaded,
        PackageFileRole::AccessInventory,
    )
    .expect("legacy packaged access inventory remains readable");
    assert_eq!(effective_physical_names, packaged_physical_names);
    assert_eq!(effective_queries, packaged_queries);
    validate_predecessor_temporal_value_kinds(&legacy_entities, &effective_queries)
        .expect("legacy temporal query values remain typed");
    let governed = package_predecessor_governed_model(&manifest, &loaded)
        .expect("legacy governed model remains readable");
    validate_predecessor_registry_bindings(&manifest, &governed)
        .expect("legacy governed model remains bound to its inventories");

    let predecessor = load_predecessor_package(&root, &local_package_context())
        .expect("the exact supported legacy package remains a planning baseline");
    assert_eq!(
        predecessor.migration_baseline().engine_features,
        legacy_engine_features()
    );

    let manifest = fs::read(root.join(MANIFEST_PATH)).expect("fixture manifest reads");
    let unknown = String::from_utf8(manifest)
        .expect("fixture manifest is UTF-8")
        .replace("caller_scoped_idempotency", "future_engine_feature");
    assert_eq!(
        parse_package_envelope(unknown.as_bytes()).err(),
        Some(PackageError::CanonicalJson),
        "unknown engine features do not become supported legacy input"
    );
}

