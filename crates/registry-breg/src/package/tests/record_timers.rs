#[test]
fn unchanged_pre_timer_store_registry_plans_one_engine_transition_without_authored_ddl() {
    let root = native_minimal_package();
    let predecessor = load_predecessor_package(&root, &local_package_context())
        .expect("the exact supported legacy package remains a planning baseline");
    let source = fs::read(root.join("source/registry.yaml")).expect("fixture source reads");
    let project = parse_project_yaml(&source).expect("fixture source parses");
    let candidate = compile_project(&project, &[], CompileProfile::Production)
        .expect("the current compiler accepts the timer-free project");
    let mut baseline = predecessor.migration_baseline().clone();
    baseline.generated_ddl_sha256 = Some(digest(candidate.ddl().script().as_bytes()));

    let changes = compiled_registry_change_set_from_baseline(
        &baseline,
        &candidate,
        predecessor.package_digest(),
    );
    assert_eq!(changes.changes.len(), 1, "{:#?}", changes.changes);
    assert_eq!(
        serde_json::to_value(&changes.changes[0]).expect("change serializes"),
        json!({
            "class":"compatible-additive",
            "code":"record-timer-store-added",
            "target":{"kind":"registry"}
        })
    );
    let plan = change_set_to_applicable_migration_plan(&changes)
        .expect("the engine-owned store transition is automatically applicable");
    assert!(
        plan.statements.is_empty(),
        "engine schema is not authored SQL"
    );
    assert_eq!(plan.changes, changes.changes);
    assert_eq!(
        plan.prior_baseline
            .as_ref()
            .expect("successor retains its predecessor baseline")
            .engine_features,
        legacy_engine_features()
    );
}

#[test]
#[cfg(feature = "tooling")]
fn legacy_successor_without_baseline_feature_member_remains_a_verified_predecessor() {
    let initial_root = native_minimal_package();
    let predecessor = load_predecessor_package(&initial_root, &local_package_context())
        .expect("the immutable legacy initial package is a predecessor");
    let project_bytes =
        fs::read(initial_root.join("source/registry.yaml")).expect("fixture source reads");
    let fixture_journeys =
        fs::read(initial_root.join(FIXTURE_JOURNEYS_PATH)).expect("fixture journeys read");
    let mut prepared = prepare_package(PackageBuildRequest {
        from_package_digest: Some(predecessor.package_digest().to_owned()),
        compiler_source_revision: "native-minimal-format-fixture".to_owned(),
        schema_fingerprint: predecessor.schema_fingerprint().to_owned(),
        project: PackageSourceFile {
            path: "source/registry.yaml".to_owned(),
            bytes: project_bytes,
        },
        modules: Vec::new(),
        fixture_journeys: PackageSourceFile {
            path: FIXTURE_JOURNEYS_PATH.to_owned(),
            bytes: fixture_journeys,
        },
        migration_plan: PackageMigrationPlanInput::SuccessorFromBaseline {
            prior_baseline: Box::new(predecessor.migration_baseline().clone()),
        },
    })
    .expect("current tooling prepares the successor closure");

    prepared.manifest.engine_features = legacy_engine_features();
    prepared
        .manifest
        .migration_plan
        .changes
        .retain(|change| change.code != CompiledRegistryChangeCode::RecordTimerStoreAdded);
    prepared
        .manifest
        .migration_plan
        .prior_baseline
        .as_mut()
        .expect("successor carries its prior baseline")
        .engine_features
        .clear();
    let plan_bytes = canonicalize_json(
        &serde_json::to_value(&prepared.manifest.migration_plan)
            .expect("legacy migration plan serializes"),
    )
    .expect("legacy migration plan canonicalizes");
    prepared.files.insert(
        "database/migration-plan.json".to_owned(),
        plan_bytes.clone(),
    );
    let entry = prepared
        .manifest
        .files
        .iter_mut()
        .find(|entry| entry.role == PackageFileRole::MigrationPlan)
        .expect("successor manifest carries the migration plan");
    entry.size = u64::try_from(plan_bytes.len()).expect("plan size is bounded");
    entry.sha256 = digest(&plan_bytes);

    let temporary_parent = std::env::temp_dir()
        .canonicalize()
        .expect("temporary directory resolves without symbolic links");
    let temporary =
        tempfile::tempdir_in(temporary_parent).expect("temporary package parent exists");
    let root = temporary.path().join("legacy-successor");
    let shared = prepared
        .publish_to_directory(&root)
        .expect("legacy successor closure publishes");
    let manifest: Value = serde_json::from_slice(
        &fs::read(root.join(MANIFEST_PATH)).expect("legacy successor manifest reads"),
    )
    .expect("legacy successor manifest parses");
    assert!(manifest["manifest"]["migrationPlan"]["priorBaseline"]
        .get("engineFeatures")
        .is_none());
    assert_eq!(
        load_package(&root, &local_package_context()).err(),
        Some(PackageError::EngineFeatureUpgradeRequired)
    );

    let loaded = load_predecessor_package(&root, &local_package_context())
        .expect("known legacy successor remains a predecessor");
    assert_eq!(loaded.package_digest(), shared.digest());
    assert_eq!(
        loaded.migration_baseline().engine_features,
        legacy_engine_features()
    );
    let (rehearsed, current_registry) =
        load_predecessor_rehearsal_baseline(&root, &local_package_context())
            .expect("known legacy successor remains a rehearsal baseline");
    assert_eq!(rehearsed.package_digest(), shared.digest());
    assert_eq!(current_registry.registry_id(), loaded.package_id());

    let mut missing = loaded.migration_baseline().clone();
    missing.engine_features.clear();
    assert_eq!(
        validate_migration_baseline(&missing).err(),
        Some(PackageError::MigrationPlan),
        "missing baseline features are accepted only through verified legacy reconstruction"
    );
}

#[test]
fn timer_policy_add_change_and_removal_are_explicit_reviewed_changes() {
    let without_timer = compile(&source(None, true));
    let primary = compile(&source(Some("activates-at"), true));
    let alternate = compile(&source(Some("alternate-activates-at"), true));

    let added = compiled_registry_change_set(&without_timer, &primary, PRIOR_PACKAGE);
    assert_timer_change(&added, CompiledRegistryChangeCode::TimerAdded);
    #[cfg(feature = "tooling")]
    {
        let classified = classify_registry_diff(&without_timer, &primary, PRIOR_PACKAGE);
        assert!(classified.changes.iter().any(|change| {
            change.change.code == CompiledRegistryChangeCode::TimerAdded
                && change.classification == DiffClassification::AccessChange
        }));
    }
    assert!(added
        .changes
        .iter()
        .any(|change| change.code == CompiledRegistryChangeCode::ActionAdded));

    let changed = compiled_registry_change_set(&primary, &alternate, PRIOR_PACKAGE);
    assert_timer_change(&changed, CompiledRegistryChangeCode::TimerChanged);
    assert_eq!(changed.changes.len(), 1, "{:#?}", changed.changes);

    let removed = compiled_registry_change_set(&primary, &without_timer, PRIOR_PACKAGE);
    assert_timer_change(&removed, CompiledRegistryChangeCode::TimerRemoved);
    assert!(removed
        .changes
        .iter()
        .any(|change| change.code == CompiledRegistryChangeCode::ActionRemoved));
}

#[test]
fn timer_change_closes_over_action_semantics_and_stable_recompile_is_empty() {
    let before = compile(&source(Some("activates-at"), true));
    let stable = compile(&source(Some("activates-at"), true));
    let unchanged = compiled_registry_change_set(&before, &stable, PRIOR_PACKAGE);
    assert!(unchanged.changes.is_empty(), "{:#?}", unchanged.changes);

    let action_changed = compile(&source(Some("activates-at"), false));
    let changes = compiled_registry_change_set(&before, &action_changed, PRIOR_PACKAGE);
    assert_timer_change(&changes, CompiledRegistryChangeCode::TimerChanged);
    assert!(changes
        .changes
        .iter()
        .any(|change| change.code == CompiledRegistryChangeCode::ActionChanged));
    assert_eq!(
        changes
            .changes
            .iter()
            .filter(|change| change.target.kind == CompiledRegistryChangeTargetKind::Timer)
            .count(),
        1,
        "{:#?}",
        changes.changes
    );
}

#[test]
fn serialized_timer_change_uses_the_closed_timer_vocabulary() {
    let before = compile(&source(None, true));
    let after = compile(&source(Some("activates-at"), true));
    let changes = compiled_registry_change_set(&before, &after, PRIOR_PACKAGE);
    let timer = changes
        .changes
        .iter()
        .find(|change| change.code == CompiledRegistryChangeCode::TimerAdded)
        .expect("timer addition is explicit");
    assert_eq!(
        serde_json::to_value(timer).expect("timer change serializes"),
        json!({
            "class":"access-or-disclosure-change",
            "code":"timer-added",
            "target":{"kind":"timer","recordTypeId":"contact","memberId":"activate"}
        })
    );
}

fn assert_timer_change(changes: &CompiledRegistryChangeSet, code: CompiledRegistryChangeCode) {
    let timer = changes
        .changes
        .iter()
        .find(|change| change.code == code)
        .unwrap_or_else(|| panic!("{code:?} is explicit: {:#?}", changes.changes));
    assert_eq!(
        timer.class,
        CompiledRegistryChangeClass::AccessOrDisclosureChange
    );
    assert_eq!(timer.target.kind, CompiledRegistryChangeTargetKind::Timer);
    assert_eq!(timer.target.record_type_id.as_deref(), Some("contact"));
    assert_eq!(timer.target.member_id.as_deref(), Some("activate"));
    assert!(
        change_set_to_applicable_migration_plan(changes).is_err(),
        "autonomous timer policy changes require reviewed activation"
    );
}

