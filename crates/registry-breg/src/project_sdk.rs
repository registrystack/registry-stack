//! Project-scoped language contracts emitted from the normalized compiler model.

use super::*;
use std::fmt::Write;

pub(super) fn generate(
    artifacts: &mut BTreeMap<String, GeneratedArtifact>,
    entities: &BTreeMap<String, CompiledEntity>,
    actions: &CompiledActionInventory,
) {
    let mut ts = String::from("// Generated by BReg. Edit the project, then regenerate.\n");
    ts.push_str(TYPESCRIPT_CONTRACT);
    let mut py = String::from("# Generated by BReg. Edit the project, then regenerate.\nfrom __future__ import annotations\nfrom typing import TypedDict, NotRequired, Literal, Protocol, TypeVar, Generic\n\n");
    py.push_str(PYTHON_CONTRACT);
    for entity in entities.values() {
        let fields = entity.stored_fields.iter().map(|field| {
            (field.logical.api_name.as_str(), field_schema(&field.logical.field_type), field.required)
        }).collect::<Vec<_>>();
        write_types(&mut ts, &mut py, &entity.api_name, &fields);
    }
    for action in &actions.actions {
        let name = type_name(&action.api_name);
        let fields = action.inputs.iter().map(|input| {
            (input.api_name.as_str(), field_schema(&input.field_type), input.required)
        }).collect::<Vec<_>>();
        write_types(&mut ts, &mut py, &format!("{name}Input"), &fields);
        let codes = action.handler.as_ref().map(|function| function.refusals.keys().map(String::as_str).collect::<Vec<_>>()).unwrap_or_default();
        let ts_codes = codes.iter().map(|code| quote(code)).collect::<Vec<_>>().join(" | ");
        let py_codes = codes.iter().map(|code| quote(code)).collect::<Vec<_>>().join(", ");
        writeln!(ts, "export type {name}Refusal = EngineReason{};", if codes.is_empty() { String::new() } else { format!(" | {ts_codes}") }).unwrap();
        writeln!(py, "{name}Refusal = EngineReason{}\n", if codes.is_empty() { String::new() } else { format!(" | Literal[{py_codes}]") }).unwrap();
        if matches!(action.execution, crate::model::CompiledActionExecution::Proposal { .. }) {
            writeln!(ts, "export type {name}Result = Proposal<{name}Input, {name}Refusal>;\n").unwrap();
            writeln!(py, "{name}Result = Proposal[{name}Input]\n").unwrap();
        } else {
            writeln!(ts, "export interface {name}Result {{ readonly action: {}; readonly applicationId: string; readonly results: {{", quote(&action.id)).unwrap();
            for effect in action.effects.iter().filter(|effect| action.result_effects.contains(&effect.id)) {
                let target = &entities[&effect.target.entity_id];
                writeln!(ts, "  readonly {}: RecordReference<{}>;", quote(&effect.id), target.api_name).unwrap();
            }
            ts.push_str("} }\n");
            writeln!(py, "{name}Result = TypedDict({}, {{\"action\": Literal[{}], \"applicationId\": str, \"results\": dict[str, RecordReference]}})\n", quote(&format!("{name}Result")), quote(&action.id)).unwrap();
        }
    }
    ts.push_str("export interface ProjectRecords {\n");
    for entity in entities.values() { writeln!(ts, "  {}: {};", quote(&entity.id), entity.api_name).unwrap(); }
    ts.push_str("}\nexport interface ProjectActions {\n");
    for action in &actions.actions {
        let name = type_name(&action.api_name);
        writeln!(ts, "  {}: {{ input: {name}Input; result: {name}Result }};", quote(&action.id)).unwrap();
    }
    ts.push_str("}\nexport interface ProjectRelationships {\n");
    for entity in entities.values() {
        writeln!(ts, "  {}: {{", quote(&entity.id)).unwrap();
        for field in entity.fields.values() {
            let FieldTypeSource::Reference { target, .. } = &field.field_type else { continue };
            let Some(target_entity) = entities.get(target) else { continue };
            writeln!(ts, "    {}: {}{};", quote(&entity.stored_fields.iter().find(|stored| stored.logical.id == field.id).expect("compiled field has logical identity").logical.api_name), target_entity.api_name, if field.required { "" } else { " | null" }).unwrap();
            if let Some(inverse) = field.relationship.as_ref().and_then(|relationship| relationship.inverse_name.as_ref()) {
                // Inverse names are emitted on their target below as independent entries.
                let _ = inverse;
            }
        }
        for source in entities.values() {
            for field in source.fields.values() {
                if matches!(&field.field_type, FieldTypeSource::Reference { target, .. } if target == &entity.id) {
                    if let Some(inverse) = field.relationship.as_ref().and_then(|relationship| relationship.inverse_name.as_ref()) {
                        writeln!(ts, "    {}: readonly {}[];", quote(inverse), source.api_name).unwrap();
                    }
                }
            }
        }
        ts.push_str("  };\n");
    }
    ts.push_str("}\n");
    ts.push_str(TYPESCRIPT_CLIENT);
    insert_bytes(artifacts, "generated/sdk/project.ts", "text/typescript", ts.into_bytes());
    insert_bytes(artifacts, "generated/sdk/project.py", "text/x-python", py.into_bytes());
}

fn quote(value: &str) -> String { serde_json::to_string(value).expect("string serializes") }
fn type_name(value: &str) -> String {
    let mut chars = value.chars();
    chars.next().map(|first| first.to_uppercase().collect::<String>() + chars.as_str()).unwrap_or_default()
}
fn write_types(ts: &mut String, py: &mut String, name: &str, fields: &[(&str, Value, bool)]) {
    writeln!(ts, "export interface {name} {{").unwrap();
    writeln!(py, "{name} = TypedDict({}, {{", quote(name)).unwrap();
    for (name, schema, required) in fields {
        writeln!(ts, "  readonly {}{}: {};", quote(name), if *required { "" } else { "?" }, schema_type(schema, false)).unwrap();
        let value = schema_type(schema, true);
        writeln!(py, "    {}: {},", quote(name), if *required { value } else { format!("NotRequired[{value}]") }).unwrap();
    }
    ts.push_str("}\n\n"); py.push_str("})\n\n");
}
fn schema_type(schema: &Value, python: bool) -> String {
    if let Some(values) = schema.get("enum").and_then(Value::as_array) {
        let values = values.iter().map(|value| serde_json::to_string(value).unwrap()).collect::<Vec<_>>();
        return if python { format!("Literal[{}]", values.join(", ")) } else { values.join(" | ") };
    }
    match schema.get("type").and_then(Value::as_str) {
        Some("string") => if python { "str" } else { "string" },
        Some("boolean") => if python { "bool" } else { "boolean" },
        Some("integer") => if python { "int" } else { "number" },
        Some("number") => if python { "float" } else { "number" },
        Some("array") => return format!("{}{}{}", if python { "list[" } else { "ReadonlyArray<" }, schema_type(&schema["items"], python), if python { "]" } else { ">" }),
        _ => if python { "dict[str, object]" } else { "Readonly<Record<string, unknown>>" },
    }.to_owned()
}

const TYPESCRIPT_CONTRACT: &str = r#"
export type EngineReason = 'pending-review' | 'stale-revision' | 'contract-changed' | 'dependency-outage' | 'invalid-input';
export type RecoveryHint = 'refresh' | 'retry' | 'correct-input' | 'terminal';
export type Availability<R extends string = EngineReason> =
  | { readonly available: true; readonly observedRevision: string }
  | { readonly available: false; readonly observedRevision: string; readonly reason: R; readonly recovery: RecoveryHint };
export interface RecordReference<T> { readonly recordType: string; readonly recordId: string; readonly revision: number; readonly data?: T }
export interface RecordView<T> { readonly id: string; readonly revision: string; readonly title: string; readonly data: T }
export interface Proposal<I, R extends string = EngineReason> { readonly id: string; readonly actionId: string; readonly revision: string; readonly state: string; readonly inputs?: I; readonly transitions: Readonly<Partial<Record<'submit'|'revise'|'cancel'|'apply', Availability<R>>>> }
export interface Page<T> { readonly items: readonly T[]; readonly nextCursor?: string }
"#;
const TYPESCRIPT_CLIENT: &str = r#"
/** The native generic client supplies these metadata-promoted operations. */
export interface ProjectClient {
  read<K extends keyof ProjectRecords>(recordType: K, id: string): Promise<RecordView<ProjectRecords[K]>>;
  related<K extends keyof ProjectRelationships, R extends keyof ProjectRelationships[K]>(recordType: K, id: string, relationship: R): Promise<ProjectRelationships[K][R]>;
  invoke<K extends keyof ProjectActions>(action: K, input: ProjectActions[K]['input'], idempotencyKey: string): Promise<ProjectActions[K]['result']>;
  listProposals<K extends keyof ProjectActions>(action: K, cursor?: string): Promise<Page<Proposal<ProjectActions[K]['input']>>>;
  resumeProposal<K extends keyof ProjectActions>(action: K, id: string): Promise<Proposal<ProjectActions[K]['input']>>;
}
"#;
const PYTHON_CONTRACT: &str = r#"
EngineReason = Literal['pending-review', 'stale-revision', 'contract-changed', 'dependency-outage', 'invalid-input']
RecoveryHint = Literal['refresh', 'retry', 'correct-input', 'terminal']
class Availability(TypedDict):
    available: bool
    observedRevision: str
    reason: NotRequired[EngineReason]
    recovery: NotRequired[RecoveryHint]
class RecordReference(TypedDict):
    recordType: str
    recordId: str
    revision: int
I = TypeVar('I')
class Proposal(TypedDict, Generic[I]):
    id: str
    actionId: str
    revision: str
    state: str
    inputs: NotRequired[I]
    transitions: dict[str, Availability]

"#;
