use crate::report;

/// The default directory the generated schemas are written to, relative to
/// the repository root the command runs from.
pub const DEFAULT_OUTPUT_DIR: &str = "products/adapter/schemas";

#[derive(Debug, Args)]
pub struct SchemasArgs {
    /// Compare the generated bytes with the committed files and refuse on
    /// drift instead of writing anything.
    #[arg(long)]
    pub check: bool,

    /// Directory the generated schemas are written to or compared against.
    #[arg(long, value_name = "DIRECTORY", default_value_t = DEFAULT_OUTPUT_DIR.to_owned())]
    pub output_dir: String,
}

/// One generated schema: its file name, its derived document, and the
/// identity members the envelope adds.
struct Entry {
    file: &'static str,
    derived: Value,
    title: &'static str,
    schema_id: &'static str,
    api_version: &'static str,
    kind: &'static str,
}

