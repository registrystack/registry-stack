/// The five generated schema documents, keyed by file name. Deterministic:
/// the same workspace state renders the same bytes.
pub fn documents() -> Result<BTreeMap<&'static str, String>, serde_json::Error> {
    let shared: Value =
        serde_json::from_str(&registry_platform_config::schema::shared_blocks_document()?)?;
    let shared: BTreeSet<String> = shared
        .get("$defs")
        .and_then(Value::as_object)
        .map(|definitions| definitions.keys().cloned().collect())
        .unwrap_or_default();
    let mut documents = BTreeMap::new();
    for entry in entries()? {
        let mut derived = entry.derived;
        // The reader refuses `null` in every authored member (CFG-EMPTY-1),
        // so drop the `null` schemars adds to optional members; the platform
        // shared blocks keep the exact definitions the platform publishes.
        refuse_null_outside_shared_blocks(&mut derived, &shared);
        set_const(&mut derived, "apiVersion", entry.api_version);
        set_const(&mut derived, "kind", entry.kind);
        let mut object = match derived {
            Value::Object(object) => object,
            _ => unreachable!("schemars derives a schema object for a struct"),
        };
        object.insert(
            "$schema".to_owned(),
            Value::String("https://json-schema.org/draft/2020-12/schema".to_owned()),
        );
        object.insert("$id".to_owned(), Value::String(entry.schema_id.to_owned()));
        object.insert("title".to_owned(), Value::String(entry.title.to_owned()));
        documents.insert(entry.file, render(&Value::Object(object))?);
    }
    Ok(documents)
}

fn render(document: &Value) -> Result<String, serde_json::Error> {
    let mut rendered = serde_json::to_string_pretty(document)?;
    rendered.push('\n');
    Ok(rendered)
}

/// Drop the `null` branch schemars adds to each optional member, everywhere
/// except the shared-block definitions named in `shared`, which are embedded
/// exactly as the platform publishes them.
fn refuse_null_outside_shared_blocks(schema: &mut Value, shared: &BTreeSet<String>) {
    match schema {
        Value::Object(object) => {
            if let Some(definitions) = object.get_mut("$defs").and_then(Value::as_object_mut) {
                for (name, definition) in definitions.iter_mut() {
                    if !shared.contains(name) {
                        refuse_null(definition);
                    }
                }
            }
            for (key, member) in object.iter_mut() {
                if key != "$defs" {
                    refuse_null(member);
                }
            }
        }
        Value::Array(items) => items
            .iter_mut()
            .for_each(|item| refuse_null_outside_shared_blocks(item, shared)),
        _ => {}
    }
}

/// The reader refuses `null` in every member (CFG-EMPTY-1), so a schema must
/// not admit it either: remove the `null` branch from every `type` array and
/// `anyOf`, and a `default` of `null`.
fn refuse_null(schema: &mut Value) {
    match schema {
        Value::Object(object) => {
            if object.get("default") == Some(&Value::Null) {
                object.remove("default");
            }
            if let Some(Value::Array(types)) = object.get_mut("type") {
                types.retain(|kind| kind != "null");
                if let [only] = types.as_slice() {
                    let only = only.clone();
                    object.insert("type".to_owned(), only);
                }
            }
            if let Some(Value::Array(branches)) = object.get_mut("anyOf") {
                branches.retain(|branch| branch.get("type") != Some(&Value::from("null")));
                if let [only] = branches.as_slice() {
                    let only = only.clone();
                    object.remove("anyOf");
                    if let Value::Object(only) = only {
                        object.extend(only);
                    }
                }
            }
            for member in object.values_mut() {
                refuse_null(member);
            }
        }
        Value::Array(items) => items.iter_mut().for_each(refuse_null),
        _ => {}
    }
}

/// Pin one envelope member to its expected value. The core types describe
/// the document body only: the envelope members (`apiVersion`, `kind`) are
/// the reader's, so the generator adds them itself, required like every
/// body member the reader refuses to miss.
fn set_const(schema: &mut Value, property: &str, expected: &str) {
    let object = schema
        .as_object_mut()
        .expect("schemars derives a schema object");
    let properties = object
        .entry("properties".to_owned())
        .or_insert_with(|| Value::Object(serde_json::Map::new()))
        .as_object_mut()
        .expect("properties is an object");
    let member = properties
        .entry(property.to_owned())
        .or_insert_with(|| serde_json::json!({ "type": "string" }))
        .as_object_mut()
        .expect("a property schema is an object");
    member.insert("const".to_owned(), serde_json::json!(expected));
    let required = object
        .entry("required".to_owned())
        .or_insert_with(|| Value::Array(Vec::new()))
        .as_array_mut()
        .expect("required is an array");
    if !required.iter().any(|name| name == property) {
        required.push(serde_json::json!(property));
        required.sort_by(|left, right| {
            left.as_str()
                .unwrap_or_default()
                .cmp(right.as_str().unwrap_or_default())
        });
    }
}

/// Why the `schemas` command failed.
#[derive(Debug)]
pub(crate) enum SchemasFailure {
    /// A committed file could not be read for comparison.
    Io { path: String, source: io::Error },
    /// A committed file drifted from its generated bytes.
    Drift { files: Vec<String> },
}

/// Run the `schemas` command: write every generated document, or compare
/// them with the committed files.
pub(crate) fn run(args: &SchemasArgs) -> Result<Value, SchemasFailure> {
    let documents = documents().map_err(|error| SchemasFailure::Io {
        path: DEFAULT_OUTPUT_DIR.to_owned(),
        source: io::Error::other(error),
    })?;
    let output = PathBuf::from(&args.output_dir);
    if args.check {
        let drifted = compare(&output, &documents)?;
        if !drifted.is_empty() {
            return Err(SchemasFailure::Drift { files: drifted });
        }
        return Ok(serde_json::json!({
            "command": "schemas",
            "check": true,
            "outputDir": args.output_dir,
            "files": documents.keys().copied().collect::<Vec<_>>(),
        }));
    }
    write_all(&output, &documents)?;
    Ok(serde_json::json!({
        "command": "schemas",
        "check": false,
        "outputDir": args.output_dir,
        "files": documents.keys().copied().collect::<Vec<_>>(),
    }))
}

/// The committed files that drift from their generated bytes, in file-name
/// order. A file the directory does not hold counts as drifted.
fn compare(
    output: &Path,
    documents: &BTreeMap<&'static str, String>,
) -> Result<Vec<String>, SchemasFailure> {
    let mut drifted = Vec::new();
    for (file, generated) in documents {
        let path = output.join(file);
        let committed = std::fs::read(&path).map_err(|error| SchemasFailure::Io {
            path: path.display().to_string(),
            source: error,
        })?;
        if committed != generated.as_bytes() {
            drifted.push((*file).to_owned());
        }
    }
    Ok(drifted)
}

fn write_all(
    output: &Path,
    documents: &BTreeMap<&'static str, String>,
) -> Result<(), SchemasFailure> {
    std::fs::create_dir_all(output).map_err(|error| SchemasFailure::Io {
        path: output.display().to_string(),
        source: error,
    })?;
    for (file, contents) in documents {
        let path = output.join(file);
        std::fs::write(&path, contents).map_err(|error| SchemasFailure::Io {
            path: path.display().to_string(),
            source: error,
        })?;
    }
    Ok(())
}

/// The exit class and diagnostics of a `schemas` failure, written by the
/// shared failure path in `lib.rs`.
pub(crate) fn failure(failure: &SchemasFailure) -> (u8, Vec<Value>) {
    match failure {
        SchemasFailure::Io { path, source } => (
            report::OPERATIONAL_FAILURE_EXIT,
            vec![serde_json::json!({
                "severity": "error",
                "code": "adapterctl.io-failure",
                "artifact": "filesystem",
                "path": path,
                "message": format!("the generated schemas could not be compared or written: {source}"),
                "suggestedAction": "Correct the path or permissions, then retry.",
            })],
        ),
        SchemasFailure::Drift { files } => (
            report::DOMAIN_REFUSAL_EXIT,
            vec![serde_json::json!({
                "severity": "error",
                "code": "adapterctl.schemas.drift",
                "artifact": "generated-schemas",
                "path": DEFAULT_OUTPUT_DIR,
                "message": format!(
                    "the committed schemas drifted from the model: {}",
                    files.join(", ")
                ),
                "suggestedAction": "Run `adapterctl schemas` from the repository root and commit the regenerated files.",
            })],
        ),
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    /// The generated documents are deterministic and carry the mandated
    /// `$id` for each format.
    #[test]
    fn documents_are_deterministic_and_versioned() {
        let first = documents().unwrap();
        assert_eq!(documents().unwrap(), first);
        assert_eq!(first.len(), 5);
        for (file, contents) in &first {
            let document: Value = serde_json::from_str(contents).unwrap();
            let id = document["$id"].as_str().unwrap();
            assert_eq!(
                Path::new(id).file_name().unwrap().to_str().unwrap(),
                *file,
                "the file name is the last segment of the $id"
            );
            assert_eq!(
                document["$schema"],
                "https://json-schema.org/draft/2020-12/schema"
            );
            assert!(document["properties"]["apiVersion"]["const"].is_string());
            assert!(document["properties"]["kind"]["const"].is_string());
        }
        let runtime: Value = serde_json::from_str(&first["runtime.v1alpha1.schema.json"]).unwrap();
        assert_eq!(runtime["$id"], ADAPTER_RUNTIME_SCHEMA_ID,);
        assert_eq!(
            runtime["properties"]["apiVersion"]["const"],
            ADAPTER_RUNTIME_API_VERSION
        );
        assert_eq!(runtime["properties"]["kind"]["const"], ADAPTER_RUNTIME_KIND);
    }

    /// The runtime schema's shared blocks keep the platform's definitions
    /// (which admit `null` where the platform publishes it), while every
    /// Adapter-owned optional member refuses `null` (CFG-EMPTY-1). The
    /// runtime embeds the listener, database, and OIDC issuer blocks; any
    /// shared block it carries is byte-exact.
    #[test]
    fn shared_blocks_stay_exact_and_adapter_members_refuse_null() {
        let shared: Value = serde_json::from_str(
            &registry_platform_config::schema::shared_blocks_document().unwrap(),
        )
        .unwrap();
        let shared = shared["$defs"].as_object().unwrap();
        let runtime: Value =
            serde_json::from_str(&documents().unwrap()["runtime.v1alpha1.schema.json"]).unwrap();
        let definitions = runtime["$defs"].as_object().unwrap();
        for embedded in ["DatabaseConfig", "ListenerConfig", "OidcIssuerConfig"] {
            assert!(
                definitions.contains_key(embedded),
                "the runtime schema must carry {embedded}"
            );
        }
        for (name, definition) in shared {
            if let Some(carried) = definitions.get(name) {
                assert_eq!(carried, definition, "shared block {name} must stay exact");
            }
        }
        // `allowedPrivateCidrs` is an optional Adapter member: its schema
        // must not admit `null`.
        let cidrs = &definitions["Cidr"];
        assert!(
            cidrs.get("type").and_then(Value::as_str) == Some("string"),
            "{cidrs}"
        );
    }

    /// A committed file that differs from its generated bytes drifts.
    #[test]
    fn a_hand_edited_file_drifts() {
        let root = tempfile::tempdir().unwrap();
        let output = root.path().join("schemas");
        write_all(&output, &documents().unwrap()).unwrap();
        let profile = output.join("profile.v1alpha1.schema.json");
        let edited = std::fs::read_to_string(&profile).unwrap().replacen(
            "\"Registry Adapter facade profile\"",
            "\"Hand edited\"",
            1,
        );
        std::fs::write(&profile, edited).unwrap();
        let drifted = compare(&output, &documents().unwrap()).unwrap();
        assert_eq!(drifted, vec!["profile.v1alpha1.schema.json"]);
    }
}
