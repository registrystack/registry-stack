/// An exact keyed selection from an array: the element whose `key` member
/// equals `value`.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct KeyFilter {
    pub key: String,
    pub value: String,
}

/// One dotted segment: a member name, optionally followed by a keyed filter.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct PathSegment {
    pub name: String,
    pub filter: Option<KeyFilter>,
}

/// Why a path or selector is outside the grammar. The texts carry positions
/// and bounds, never the offending text.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum PathError {
    Empty,
    TooLong,
    TooManySegments,
    UnexpectedCharacter { position: usize },
    UnterminatedQuote { position: usize },
    QuotedEmpty { position: usize },
    QuotedTooLong { position: usize },
    QuotedCharacter { position: usize },
    MalformedFilter { position: usize },
    TrailingSeparator,
    FilterNotAllowed,
}

impl PathError {
    /// A value-free description naming the position or bound.
    #[must_use]
    pub fn describe(self) -> String {
        match self {
            Self::Empty => "the path is empty".to_string(),
            Self::TooLong => {
                format!("the path is longer than {MAXIMUM_MAPPING_PATH_CHARACTERS} characters")
            }
            Self::TooManySegments => {
                format!("the path has more than {MAXIMUM_MAPPING_PATH_SEGMENTS} segments")
            }
            Self::UnexpectedCharacter { position } => {
                format!("unexpected character at position {position}")
            }
            Self::UnterminatedQuote { position } => {
                format!("the quoted text starting at position {position} is not closed")
            }
            Self::QuotedEmpty { position } => {
                format!("the quoted text at position {position} is empty")
            }
            Self::QuotedTooLong { position } => format!(
                "the quoted text at position {position} is longer than \
                 {MAXIMUM_MAPPING_QUOTED_CHARACTERS} characters"
            ),
            Self::QuotedCharacter { position } => format!(
                "the quoted text at position {position} holds a character outside printable \
                 ASCII, or a quote or backslash"
            ),
            Self::MalformedFilter { position } => {
                format!("the filter at position {position} is not [name = \"value\"]")
            }
            Self::TrailingSeparator => "the path ends with a dot".to_string(),
            Self::FilterNotAllowed => "a target path carries no filter".to_string(),
        }
    }
}

/// Parse a selector: dotted segments, each a name or quoted key, each
/// optionally carrying an exact keyed filter.
pub fn parse_selector(text: &str) -> Result<Vec<PathSegment>, PathError> {
    Parser::new(text)?.segments()
}

/// Parse a target path: the selector grammar without filters. Returns the
/// member names.
pub fn parse_target_path(text: &str) -> Result<Vec<String>, PathError> {
    let segments = parse_selector(text)?;
    if segments.iter().any(|segment| segment.filter.is_some()) {
        return Err(PathError::FilterNotAllowed);
    }
    Ok(segments.into_iter().map(|segment| segment.name).collect())
}

struct Parser {
    characters: Vec<char>,
    position: usize,
}

impl Parser {
    fn new(text: &str) -> Result<Self, PathError> {
        if text.is_empty() {
            return Err(PathError::Empty);
        }
        let characters: Vec<char> = text.chars().collect();
        if characters.len() > MAXIMUM_MAPPING_PATH_CHARACTERS {
            return Err(PathError::TooLong);
        }
        Ok(Self {
            characters,
            position: 0,
        })
    }

    fn peek(&self) -> Option<char> {
        self.characters.get(self.position).copied()
    }

    fn segments(mut self) -> Result<Vec<PathSegment>, PathError> {
        let mut segments = Vec::new();
        loop {
            segments.push(self.segment()?);
            if segments.len() > MAXIMUM_MAPPING_PATH_SEGMENTS {
                return Err(PathError::TooManySegments);
            }
            match self.peek() {
                None => return Ok(segments),
                Some('.') => {
                    self.position += 1;
                    if self.peek().is_none() {
                        return Err(PathError::TrailingSeparator);
                    }
                }
                Some(_) => {
                    return Err(PathError::UnexpectedCharacter {
                        position: self.position,
                    })
                }
            }
        }
    }

    fn segment(&mut self) -> Result<PathSegment, PathError> {
        let name = match self.peek() {
            Some('"') => self.quoted()?,
            Some(character) if is_name_start(character) => self.name(),
            _ => {
                return Err(PathError::UnexpectedCharacter {
                    position: self.position,
                })
            }
        };
        let filter = if self.peek() == Some('[') {
            Some(self.filter()?)
        } else {
            None
        };
        Ok(PathSegment { name, filter })
    }

    fn name(&mut self) -> String {
        let start = self.position;
        while self.peek().is_some_and(is_name_continue) {
            self.position += 1;
        }
        self.characters[start..self.position].iter().collect()
    }

    fn quoted(&mut self) -> Result<String, PathError> {
        let start = self.position;
        self.position += 1;
        let mut text = String::new();
        loop {
            match self.peek() {
                None => return Err(PathError::UnterminatedQuote { position: start }),
                Some('"') => {
                    self.position += 1;
                    break;
                }
                Some(character) if is_quoted_character(character) => {
                    text.push(character);
                    self.position += 1;
                    if text.chars().count() > MAXIMUM_MAPPING_QUOTED_CHARACTERS {
                        return Err(PathError::QuotedTooLong { position: start });
                    }
                }
                Some(_) => {
                    return Err(PathError::QuotedCharacter {
                        position: self.position,
                    })
                }
            }
        }
        if text.is_empty() {
            return Err(PathError::QuotedEmpty { position: start });
        }
        Ok(text)
    }

    fn skip_spaces(&mut self) {
        while self.peek() == Some(' ') {
            self.position += 1;
        }
    }

    fn filter(&mut self) -> Result<KeyFilter, PathError> {
        let start = self.position;
        let malformed = PathError::MalformedFilter { position: start };
        self.position += 1;
        self.skip_spaces();
        if !self.peek().is_some_and(is_name_start) {
            return Err(malformed);
        }
        let key = self.name();
        self.skip_spaces();
        if self.peek() != Some('=') {
            return Err(malformed);
        }
        self.position += 1;
        self.skip_spaces();
        if self.peek() != Some('"') {
            return Err(malformed);
        }
        let value = self.quoted()?;
        if self.peek() != Some(']') {
            return Err(malformed);
        }
        self.position += 1;
        Ok(KeyFilter { key, value })
    }
}

fn is_name_start(character: char) -> bool {
    character.is_ascii_alphabetic() || character == '_'
}

fn is_name_continue(character: char) -> bool {
    character.is_ascii_alphanumeric() || character == '_'
}

fn is_quoted_character(character: char) -> bool {
    (' '..='~').contains(&character) && character != '"' && character != '\\'
}

/// Whether `text` is a plain name segment (no quoting needed).
fn is_plain_name(text: &str) -> bool {
    let mut characters = text.chars();
    characters.next().is_some_and(is_name_start) && characters.all(is_name_continue)
}

/// A readable form of a schema-side path: plain names bare, other names
/// quoted.
fn render_path(path: &[String]) -> String {
    path.iter()
        .map(|name| {
            if is_plain_name(name) {
                name.clone()
            } else {
                format!("\"{name}\"")
            }
        })
        .collect::<Vec<_>>()
        .join(".")
}

