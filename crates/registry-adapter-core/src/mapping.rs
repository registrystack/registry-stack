/// The authored mapping model.
#[cfg_attr(feature = "schema", derive(schemars::JsonSchema))]
#[derive(Clone, Debug, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase", deny_unknown_fields)]
pub struct AdapterMapping {
    /// The format envelope version.
    pub api_version: String,
    /// The format kind: `AdapterMapping`.
    pub kind: String,
    /// What the mapping targets and where its generated script lives.
    pub mapping: MappingHeader,
    /// The ordered field assignments.
    pub assignments: Vec<Assignment>,
}

impl AdapterMapping {
    /// Whether the envelope members carry this format's fixed names.
    #[must_use]
    pub fn has_current_envelope(&self) -> bool {
        self.api_version == ADAPTER_MAPPING_API_VERSION && self.kind == ADAPTER_MAPPING_KIND
    }
}

/// The mapping's identity, target, and generated-script location. Every path
/// resolves against the model file's directory.
