    #[test]
    fn header_round_trips_and_rejects_edits() {
        let m = model(json!([]));
        let reference = model_reference_from("scripts/p.rhai", "person.mapping.yaml");
        let script = generate(&m, &schema(), &reference, DIGEST).unwrap();
        assert_eq!(
            parse_generated_header(&script),
            GeneratedHeaderState::Parsed(GeneratedHeader {
                model_reference: reference,
                model_digest: DIGEST.to_string()
            })
        );
        // Handwritten scripts have no header at all.
        assert_eq!(
            parse_generated_header("fn f(x) { x }\n"),
            GeneratedHeaderState::Absent
        );
        assert_eq!(parse_generated_header(""), GeneratedHeaderState::Absent);
        assert_eq!(
            parse_generated_header("// handwritten\nfn f(x) { x }\n"),
            GeneratedHeaderState::Absent
        );
        // A script that opens with the marker but whose header does not
        // parse exactly was generated and then edited: malformed.
        let malformed = |text: &str| {
            assert_eq!(
                parse_generated_header(text),
                GeneratedHeaderState::Malformed,
                "{text}"
            );
        };
        malformed(&script.replacen(
            "Generated by adapterctl from",
            "Generated by adapterctl  from",
            1,
        ));
        malformed(&script.replacen("edit the model", "edit the mode", 1));
        malformed(&script.replace('\n', "\r\n"));
        malformed(&script.replacen("digest=", "digst=", 1));
        for replacement in [
            "model=../../../etc/passwd digest=",
            "model=../p.mapping.yaml  digest=",
            "model=p.yaml digest=",
            "model=/abs/p.mapping.yaml digest=",
            "model=../.p.mapping.yaml digest=",
            "model=../a/../p.mapping.yaml digest=",
        ] {
            let third = format!("// adapterctl-mapping: {replacement}{DIGEST}");
            let altered: String = script
                .lines()
                .enumerate()
                .map(|(i, line)| {
                    if i == 2 {
                        third.clone()
                    } else {
                        line.to_string()
                    }
                })
                .collect::<Vec<_>>()
                .join("\n");
            assert_eq!(
                parse_generated_header(&altered),
                GeneratedHeaderState::Malformed,
                "{replacement}"
            );
        }
        malformed(&script.replacen(DIGEST, "sha256:abc", 1));
        malformed(&script.replacen(DIGEST, &format!("{DIGEST} "), 1));
        // Only the marker line and a two-line stub are still malformed.
        malformed("// Generated by adapterctl from an AdapterMapping model; edit the model and regenerate.\n");
        assert!(parsed(&script).is_some());
    }

