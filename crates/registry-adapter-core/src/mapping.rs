/// The model path and digest a generated script carries in its header.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct GeneratedHeader {
    /// The model path relative to the script's directory.
    pub model_reference: String,
    /// `sha256:` and 64 lowercase hex digits over the parsed model,
    /// serialized as JSON, so a layout-only edit to the file keeps it.
    pub model_digest: String,
}

/// The model path as seen from the script's directory: one `../` per
/// directory level of `script_path`, then the model file name. Both the
/// script path and the model file are relative to the model's directory.
#[must_use]
pub fn model_reference_from(script_path: &str, model_file_name: &str) -> String {
    let depth = script_path.matches('/').count();
    format!("{}{model_file_name}", "../".repeat(depth))
}

fn model_reference_is_valid(reference: &str) -> bool {
    let mut rest = reference;
    while let Some(stripped) = rest.strip_prefix("../") {
        rest = stripped;
    }
    let Some(name) = rest.strip_suffix(MODEL_FILE_SUFFIX) else {
        return false;
    };
    !name.is_empty()
        && !name.starts_with('.')
        && !name.contains("..")
        && name
            .chars()
            .all(|character| character.is_ascii_alphanumeric() || "_-.".contains(character))
}

fn model_digest_is_valid(digest: &str) -> bool {
    digest.strip_prefix("sha256:").is_some_and(|hex| {
        hex.len() == 64
            && hex
                .bytes()
                .all(|byte| matches!(byte, b'0'..=b'9' | b'a'..=b'f'))
    })
}

/// What the first lines of a script say about its origin.
#[derive(Clone, Debug, PartialEq, Eq)]
pub enum GeneratedHeaderState {
    /// The script does not open with the generated marker: handwritten.
    Absent,
    /// The script opens with the generated marker but the header is not
    /// exactly what [`generate`] writes (a hand edit, or CRLF line endings).
    Malformed,
    /// The exact generated header.
    Parsed(GeneratedHeader),
}

/// Read the header of a generated script. Only the exact form [`generate`]
/// writes is `Parsed`; a first line that carries the generated marker with
/// any other header is `Malformed`, never silently handwritten.
#[must_use]
pub fn parse_generated_header(script_text: &str) -> GeneratedHeaderState {
    let mut lines = script_text.split('\n');
    let first = lines.next().unwrap_or_default();
    if !first.trim_end_matches('\r').starts_with(HEADER_MARKER) {
        return GeneratedHeaderState::Absent;
    }
    let parsed = (|| {
        if first != HEADER_FIRST_LINE || lines.next()? != HEADER_SECOND_LINE {
            return None;
        }
        let third = lines.next()?.strip_prefix(HEADER_THIRD_PREFIX)?;
        let (reference, digest) = third.split_once(HEADER_THIRD_DIGEST)?;
        if !model_reference_is_valid(reference) || !model_digest_is_valid(digest) {
            return None;
        }
        Some(GeneratedHeader {
            model_reference: reference.to_string(),
            model_digest: digest.to_string(),
        })
    })();
    parsed.map_or(
        GeneratedHeaderState::Malformed,
        GeneratedHeaderState::Parsed,
    )
}

/// Quote `text` as a Rhai string literal. Control characters are refused;
/// quotes and backslashes are escaped.
fn rhai_string(text: &str) -> Option<String> {
    let mut literal = String::with_capacity(text.len() + 2);
    literal.push('"');
    for character in text.chars() {
        match character {
            '"' => literal.push_str("\\\""),
            '\\' => literal.push_str("\\\\"),
            character if character.is_control() => return None,
            character => literal.push(character),
        }
    }
    literal.push('"');
    Some(literal)
}

fn literal(text: &str, pointer: &str) -> Result<String, Vec<Diagnostic>> {
    rhai_string(text).ok_or_else(|| {
        vec![finding(
            MappingCode::AssignmentInvalid,
            pointer.to_string(),
            "the text holds a control character and cannot be written into a script".to_string(),
            "Remove the control character.",
        )]
    })
}

#[derive(Default)]
struct HelperUse {
    walk: bool,
    required: bool,
    integer: bool,
    text: bool,
    date: bool,
}

enum Node {
    Leaf(String),
    Object(Vec<(String, Node)>),
}

/// Insert `leaf` at `path`, creating objects on the way. A `None` leaf
/// ensures an object exists at `path` itself. Returns false on a shape clash.
fn insert(children: &mut Vec<(String, Node)>, path: &[String], leaf: Option<String>) -> bool {
    let Some((name, rest)) = path.split_first() else {
        return true;
    };
    let existing = children.iter_mut().find(|(existing, _)| existing == name);
    if rest.is_empty() {
        return match (existing, leaf) {
            (None, Some(leaf)) => {
                children.push((name.clone(), Node::Leaf(leaf)));
                true
            }
            (None, None) => {
                children.push((name.clone(), Node::Object(Vec::new())));
                true
            }
            (Some((_, Node::Object(_))), None) => true,
            (Some(_), _) => false,
        };
    }
    match existing {
        Some((_, Node::Object(inner))) => insert(inner, rest, leaf),
        Some((_, Node::Leaf(_))) => false,
        None => {
            let mut inner = Vec::new();
            let inserted = insert(&mut inner, rest, leaf);
            children.push((name.clone(), Node::Object(inner)));
            inserted
        }
    }
}

fn render_object(children: &[(String, Node)], indent: usize) -> Result<String, Vec<Diagnostic>> {
    if children.is_empty() {
        return Ok("#{}".to_string());
    }
    let pad = " ".repeat(indent + 4);
    let mut text = String::from("#{\n");
    for (position, (name, node)) in children.iter().enumerate() {
        let key = literal(name, "/assignments")?;
        let value = match node {
            Node::Leaf(expression) => expression.clone(),
            Node::Object(inner) => render_object(inner, indent + 4)?,
        };
        let separator = if position + 1 == children.len() {
            ""
        } else {
            ","
        };
        text.push_str(&format!("{pad}{key}: {value}{separator}\n"));
    }
    text.push_str(&" ".repeat(indent));
    text.push('}');
    Ok(text)
}

fn steps_literal(segments: &[PathSegment], pointer: &str) -> Result<String, Vec<Diagnostic>> {
    let mut steps = Vec::with_capacity(segments.len());
    for segment in segments {
        let name = literal(&segment.name, pointer)?;
        steps.push(match &segment.filter {
            None => format!("[{name}]"),
            Some(filter) => format!(
                "[{name}, {}, {}]",
                literal(&filter.key, pointer)?,
                literal(&filter.value, pointer)?
            ),
        });
    }
    Ok(format!("[{}]", steps.join(", ")))
}

fn constant_literal(constant: &MappingConstant, pointer: &str) -> Result<String, Vec<Diagnostic>> {
    Ok(match constant {
        MappingConstant::Boolean(value) => value.to_string(),
        MappingConstant::Integer(i64::MIN) => "(-9223372036854775807 - 1)".to_string(),
        MappingConstant::Integer(value) => value.to_string(),
        MappingConstant::Text(text) => literal(text, pointer)?,
    })
}

fn conversion_call(conversion: Conversion) -> Option<&'static str> {
    match conversion {
        Conversion::None => None,
        Conversion::Integer => Some("mapping_integer"),
        Conversion::Text => Some("mapping_text"),
        Conversion::Date => Some("mapping_date"),
    }
}

fn mark_conversion(conversion: Conversion, used: &mut HelperUse) {
    match conversion {
        Conversion::None => {}
        Conversion::Integer => used.integer = true,
        Conversion::Text => used.text = true,
        Conversion::Date => used.date = true,
    }
}

const HELPER_WALK: &str = r#"fn mapping_walk(value, steps, path) {
    for step in steps {
        if type_of(value) != "map" || !value.contains(step[0]) {
            return ();
        }
        value = value[step[0]];
        if step.len() == 3 {
            if type_of(value) != "array" {
                return ();
            }
            let found = ();
            let count = 0;
            for item in value {
                if type_of(item) == "map" && item.contains(step[1]) && item[step[1]] == step[2] {
                    found = item;
                    count += 1;
                }
            }
            if count > 1 {
                throw "mapping.duplicate: " + path;
            }
            if count == 0 {
                return ();
            }
            value = found;
        }
    }
    value
}
"#;

const HELPER_REQUIRED: &str = r#"fn mapping_required(value, path) {
    if type_of(value) == "()" {
        throw "mapping.missing: " + path;
    }
    value
}
"#;

const HELPER_INTEGER: &str = r#"fn mapping_integer(value, path) {
    let kind = type_of(value);
    if kind == "i64" {
        return value;
    }
    if kind == "string" {
        let digits = value;
        if digits.starts_with("-") {
            digits = digits.sub_string(1);
        }
        let ok = digits.len() >= 1 && digits.len() <= 18;
        for character in digits.to_chars() {
            if character < '0' || character > '9' {
                ok = false;
            }
        }
        if ok {
            return parse_int(value);
        }
    }
    throw "mapping.conversion: " + path;
}
"#;

const HELPER_TEXT: &str = r#"fn mapping_text(value, path) {
    let kind = type_of(value);
    if kind == "string" {
        return value;
    }
    if kind == "i64" {
        return value.to_string();
    }
    throw "mapping.conversion: " + path;
}
"#;

const HELPER_DATE: &str = r#"fn mapping_date(value, path) {
    if type_of(value) == "string" && value.len() == 10 {
        let characters = value.to_chars();
        let ok = true;
        for position in 0..10 {
            if position == 4 || position == 7 {
                if characters[position] != '-' {
                    ok = false;
                }
            } else if characters[position] < '0' || characters[position] > '9' {
                ok = false;
            }
        }
        if ok {
            let year = parse_int(value.sub_string(0, 4));
            let month = parse_int(value.sub_string(5, 2));
            let day = parse_int(value.sub_string(8, 2));
            if month >= 1 && month <= 12 {
                let leap = (year % 4 == 0 && year % 100 != 0) || year % 400 == 0;
                let days = [31, if leap { 29 } else { 28 }, 31, 30, 31, 30, 31, 31, 30, 31, 30, 31];
                if day >= 1 && day <= days[month - 1] {
                    return value;
                }
            }
        }
    }
    throw "mapping.conversion: " + path;
}
"#;

/// Generate the Rhai script for `mapping`. Refuses with the check findings
/// when any check fails. The bytes depend only on the arguments.
///
/// `model_reference` is the model path relative to the script's directory
/// (see [`model_reference_from`]); `model_digest` is the `sha256:` digest of
/// the parsed model, serialized as JSON.
pub fn generate(
    mapping: &AdapterMapping,
    target_schema: &Value,
    model_reference: &str,
    model_digest: &str,
) -> Result<String, Vec<Diagnostic>> {
    let mut findings = check_mapping(mapping, target_schema);
    if let Some(file_name) = model_reference.rsplit('/').next() {
        findings.extend(check_mapping_file(mapping, file_name));
    }
    let header_reported = findings
        .iter()
        .any(|diagnostic| diagnostic.code == MappingCode::HeaderInvalid.code());
    if !header_reported
        && (!model_reference_is_valid(model_reference) || !model_digest_is_valid(model_digest))
    {
        findings.push(finding(
            MappingCode::HeaderInvalid,
            String::new(),
            "the model reference or digest cannot be written into the script header".to_string(),
            "Pass a path like ../<name>.mapping.yaml and a sha256: digest of the parsed model.",
        ));
    }
    if findings
        .iter()
        .any(|diagnostic| diagnostic.severity == Severity::Error)
    {
        return Err(findings);
    }

    let entrypoint = &mapping.mapping.entrypoint;
    let root = match mapping.mapping.target {
        MappingTarget::Consultation | MappingTarget::Evidence => "source",
        MappingTarget::Ingestion => "source",
        MappingTarget::SourceRequest => "exchange",
    };

    let mut used = HelperUse::default();
    let mut tree: Vec<(String, Node)> = Vec::new();
    let mut omitted = String::new();
    for (index, assignment) in mapping.assignments.iter().enumerate() {
        let pointer = format!("/assignments/{index}");
        let target = parse_target_path(&assignment.target).map_err(|_| unreachable_parse())?;
        let path_text = literal(&assignment.target, &format!("{pointer}/target"))?;

        if let Some(constant) = &assignment.constant {
            let expression = constant_literal(constant, &format!("{pointer}/constant"))?;
            if !insert(&mut tree, &target, Some(expression)) {
                return Err(vec![clash(&pointer)]);
            }
            continue;
        }
        let selector = assignment.from.as_deref().unwrap_or_default();
        let segments = parse_selector(selector).map_err(|_| unreachable_parse())?;
        let steps = steps_literal(&segments, &format!("{pointer}/from"))?;
        let walk = format!("mapping_walk({root}, {steps}, {path_text})");
        used.walk = true;
        mark_conversion(assignment.convert, &mut used);

        if assignment.when_missing == WhenMissing::Omit {
            let variable = format!("value_{index}");
            let converted = match conversion_call(assignment.convert) {
                Some(call) => format!("{call}({variable}, {path_text})"),
                None => variable.clone(),
            };
            let mut accessor = String::new();
            for name in &target {
                accessor.push_str(&format!("[{}]", literal(name, &pointer)?));
            }
            omitted.push_str(&format!(
                "    let {variable} = {walk};\n    if type_of({variable}) != \"()\" {{\n        out{accessor} = {converted};\n    }}\n"
            ));
            if !insert(&mut tree, &target[..target.len() - 1], None) {
                return Err(vec![clash(&pointer)]);
            }
        } else {
            used.required = true;
            let required = format!("mapping_required({walk}, {path_text})");
            let expression = match conversion_call(assignment.convert) {
                Some(call) => format!("{call}({required}, {path_text})"),
                None => required,
            };
            if !insert(&mut tree, &target, Some(expression)) {
                return Err(vec![clash(&pointer)]);
            }
        }
    }

    let body = render_object(&tree, 4)?;
    let mut script = String::new();
    script.push_str(HEADER_FIRST_LINE);
    script.push('\n');
    script.push_str(HEADER_SECOND_LINE);
    script.push('\n');
    script.push_str(&format!(
        "{HEADER_THIRD_PREFIX}{model_reference}{HEADER_THIRD_DIGEST}{model_digest}\n"
    ));
    for (needed, helper) in [
        (used.walk, HELPER_WALK),
        (used.required, HELPER_REQUIRED),
        (used.integer, HELPER_INTEGER),
        (used.text, HELPER_TEXT),
        (used.date, HELPER_DATE),
    ] {
        if needed {
            script.push('\n');
            script.push_str(helper);
        }
    }

    let build = format!("    let out = {body};\n{omitted}    out\n");
    script.push('\n');
    match mapping.mapping.target {
        MappingTarget::Consultation | MappingTarget::Evidence | MappingTarget::SourceRequest => {
            script.push_str(&format!("fn {entrypoint}({root}) {{\n{build}}}\n"));
        }
        MappingTarget::Ingestion => {
            script.push_str(&format!("fn {entrypoint}_input(source) {{\n{build}}}\n\n"));
            let wrapped = match mapping.mapping.ingestion_mode {
                Some(IngestionMode::Immediate) => format!("{entrypoint}_input(exchange.body)"),
                _ => format!(
                    "#{{\n        startInput: #{{ input: {entrypoint}_input(exchange.body) }},\n        submitBody: #{{}}\n    }}"
                ),
            };
            script.push_str(&format!(
                "fn {entrypoint}(exchange) {{\n    {wrapped}\n}}\n"
            ));
        }
    }

    if script.len() > MAXIMUM_GENERATED_SCRIPT_BYTES {
        return Err(vec![finding(
            MappingCode::ScriptTooLarge,
            "/assignments".to_string(),
            format!(
                "the generated script is larger than the engine's {MAXIMUM_GENERATED_SCRIPT_BYTES}-byte source bound"
            ),
            "Split the mapping or drop assignments the target does not need.",
        )]);
    }
    Ok(script)
}

fn clash(pointer: &str) -> Diagnostic {
    finding(
        MappingCode::TargetConflict,
        format!("{pointer}/target"),
        "this target clashes with an earlier assignment".to_string(),
        "Assign each target property once.",
    )
}

/// The checks already parsed every path; a parse failure here means the
/// checks and the generator disagree, which is a defect to surface, not hide.
fn unreachable_parse() -> Vec<Diagnostic> {
    vec![finding(
        MappingCode::SelectorInvalid,
        String::new(),
        "internal disagreement between the mapping checks and the generator".to_string(),
        "Report this as a defect.",
    )]
}

