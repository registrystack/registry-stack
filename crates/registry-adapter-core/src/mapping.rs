enum Resolution<'a> {
    Leaf(&'a Value),
    Unknown,
    Unsupported(&'static str),
    NotALeaf,
}

fn schema_type(node: &Value) -> Option<&str> {
    match node.get("type")? {
        Value::String(text) => Some(text),
        Value::Array(items) => {
            let mut candidates = items
                .iter()
                .filter_map(Value::as_str)
                .filter(|text| *text != "null");
            let first = candidate_or_none(&mut candidates)?;
            Some(first)
        }
        _ => None,
    }
}

fn candidate_or_none<'a>(candidates: &mut impl Iterator<Item = &'a str>) -> Option<&'a str> {
    let first = candidates.next()?;
    if candidates.next().is_some() {
        None
    } else {
        Some(first)
    }
}

/// Every type name a node declares; `None` when it declares no `type`.
fn type_names(node: &Value) -> Option<Vec<&str>> {
    match node.get("type")? {
        Value::String(text) => Some(vec![text.as_str()]),
        Value::Array(items) => Some(items.iter().filter_map(Value::as_str).collect()),
        _ => None,
    }
}

/// JSON equality where `5` and `5.0` are the same number. Numbers compare
/// exactly, as the runtime's schema validation does: an integer never equals
/// a float it only rounds to, nor another integer the same float rounds to.
fn json_equal(left: &Value, right: &Value) -> bool {
    match (left, right) {
        (Value::Number(left), Value::Number(right)) => number_equal(left, right),
        _ => left == right,
    }
}

fn number_equal(left: &Number, right: &Number) -> bool {
    let integer = |number: &Number| {
        number
            .as_i64()
            .map(i128::from)
            .or_else(|| number.as_u64().map(i128::from))
    };
    match (integer(left), integer(right)) {
        (Some(left), Some(right)) => left == right,
        (Some(integer), None) => right.as_f64().is_some_and(|float| float_is(float, integer)),
        (None, Some(integer)) => left.as_f64().is_some_and(|float| float_is(float, integer)),
        (None, None) => left.as_f64() == right.as_f64(),
    }
}

/// Whether `float` is exactly `integer`. Every `i64` and `u64` lies inside
/// the open range of plus or minus 2^127, where an integral float converts to
/// `i128` without loss.
fn float_is(float: f64, integer: i128) -> bool {
    float.is_finite()
        && float.fract() == 0.0
        && float.abs() < 2f64.powi(127)
        && float as i128 == integer
}

fn uses_unsupported_keyword(node: &Value) -> bool {
    UNSUPPORTED_KEYWORDS
        .iter()
        .any(|keyword| node.get(keyword).is_some())
}

fn is_array_node(node: &Value) -> bool {
    match node.get("type") {
        Some(Value::String(text)) => text == "array",
        Some(Value::Array(items)) => items.iter().any(|item| item.as_str() == Some("array")),
        _ => false,
    }
}

fn properties_of(node: &Value) -> Option<&serde_json::Map<String, Value>> {
    node.get("properties")?.as_object()
}

fn required_of(node: &Value) -> Vec<&str> {
    node.get("required")
        .and_then(Value::as_array)
        .map(|items| items.iter().filter_map(Value::as_str).collect())
        .unwrap_or_default()
}

fn resolve_target<'a>(schema: &'a Value, path: &[String]) -> Resolution<'a> {
    let mut node = schema;
    for name in path {
        if uses_unsupported_keyword(node) {
            return Resolution::Unsupported(UNSUPPORTED_KEYWORDS_REASON);
        }
        if is_array_node(node) {
            return Resolution::Unsupported("the path crosses an array");
        }
        let Some(properties) = properties_of(node) else {
            return if schema_type(node) == Some("object") {
                Resolution::Unsupported("the path crosses an object schema without properties")
            } else if node.get("type").is_none() {
                Resolution::Unsupported(
                    "the path crosses a schema node with neither type nor properties",
                )
            } else {
                Resolution::Unknown
            };
        };
        let Some(child) = properties.get(name) else {
            return Resolution::Unknown;
        };
        node = child;
    }
    if uses_unsupported_keyword(node) {
        return Resolution::Unsupported(UNSUPPORTED_KEYWORDS_REASON);
    }
    if is_array_node(node) {
        return Resolution::Unsupported("the target is an array");
    }
    if properties_of(node).is_some() || schema_type(node) == Some("object") {
        return Resolution::NotALeaf;
    }
    Resolution::Leaf(node)
}

fn root_fault(schema: &Value) -> Option<&'static str> {
    if uses_unsupported_keyword(schema) {
        return Some(
            "the schema root uses a reference, composition, conditional, or dependent keyword",
        );
    }
    if schema_type(schema) != Some("object") {
        return Some("the schema root is not an object schema");
    }
    if properties_of(schema).is_none() {
        return Some("the schema root has no properties");
    }
    None
}

fn is_rhai_identifier(text: &str) -> bool {
    is_plain_name(text)
}

fn entrypoint_fault(entrypoint: &str, target: MappingTarget) -> Option<&'static str> {
    if !is_rhai_identifier(entrypoint) {
        return Some("the entrypoint is not a Rhai identifier");
    }
    // Rhai rejects an identifier made only of underscores and digits.
    if !entrypoint
        .chars()
        .any(|character| character.is_ascii_alphabetic())
    {
        return Some("the entrypoint holds no letter");
    }
    if entrypoint.len() > MAXIMUM_MAPPING_ENTRYPOINT_CHARACTERS {
        return Some("the entrypoint is longer than the allowed bound");
    }
    if entrypoint.starts_with(MAPPING_HELPER_PREFIX) {
        return Some("the entrypoint uses the prefix reserved for generated helpers");
    }
    if RHAI_RESERVED_WORDS.contains(&entrypoint) {
        return Some("the entrypoint is a Rhai keyword or reserved word");
    }
    if HELPER_BUILTINS.contains(&entrypoint) {
        return Some("the entrypoint is a Rhai built-in the generated helpers call");
    }
    if target == MappingTarget::Ingestion
        && HELPER_BUILTINS.contains(&format!("{entrypoint}{INGESTION_INNER_SUFFIX}").as_str())
    {
        return Some("the entrypoint with the ingestion suffix is a Rhai built-in the generated helpers call");
    }
    None
}

fn constant_text_fault(text: &str) -> Option<&'static str> {
    if text.chars().count() > MAXIMUM_MAPPING_CONSTANT_CHARACTERS {
        return Some("the constant text is longer than the allowed bound");
    }
    if text.chars().any(char::is_control) {
        return Some("the constant text holds a control character");
    }
    None
}

fn is_prefix_of(shorter: &[String], longer: &[String]) -> bool {
    longer.len() >= shorter.len() && longer[..shorter.len()] == *shorter
}

/// Run every static check of `mapping` against its target schema. Findings
/// are errors addressed to a JSON pointer into the model, value-free.
#[must_use]
pub fn check_mapping(mapping: &AdapterMapping, target_schema: &Value) -> Vec<Diagnostic> {
    let mut findings = Vec::new();
    check_header(&mapping.mapping, &mut findings);

    let root_ok = match root_fault(target_schema) {
        Some(reason) => {
            findings.push(finding(
                MappingCode::SchemaUnsupported,
                "/mapping/targetSchema".to_string(),
                format!("the target schema is outside the supported subset: {reason}"),
                "Use a schema with type object and properties, nested objects, and scalar leaves.",
            ));
            false
        }
        None => true,
    };

    if mapping.assignments.len() > MAXIMUM_MAPPING_ASSIGNMENTS {
        findings.push(finding(
            MappingCode::AssignmentInvalid,
            "/assignments".to_string(),
            format!("a mapping declares at most {MAXIMUM_MAPPING_ASSIGNMENTS} assignments"),
            "Split the mapping or drop assignments the target does not need.",
        ));
    }

    let mut parsed: Vec<Option<Vec<String>>> = Vec::with_capacity(mapping.assignments.len());
    for (index, assignment) in mapping.assignments.iter().enumerate() {
        parsed.push(check_assignment(
            index,
            assignment,
            target_schema,
            &mapping.mapping.target_schema,
            root_ok,
            &mut findings,
        ));
    }

    check_conflicts(&parsed, &mut findings);
    if root_ok {
        let targets: Vec<&[String]> = parsed.iter().flatten().map(Vec::as_slice).collect();
        check_required(target_schema, &mut Vec::new(), &targets, &mut findings);
    }
    findings
}

/// The checks that need the model's own file name: the generated script must
/// not be the model it is generated from, and the name must be one the
/// script header can carry.
#[must_use]
pub fn check_mapping_file(mapping: &AdapterMapping, model_file_name: &str) -> Vec<Diagnostic> {
    let mut findings = Vec::new();
    if mapping.mapping.script == model_file_name {
        findings.push(finding(
            MappingCode::PathInvalid,
            "/mapping/script".to_string(),
            "mapping.script is the model file itself".to_string(),
            "Point the script at its own new path.",
        ));
    }
    if !model_reference_is_valid(&model_reference_from(
        &mapping.mapping.script,
        model_file_name,
    )) {
        findings.push(finding(
            MappingCode::HeaderInvalid,
            "/mapping/script".to_string(),
            "the model file name cannot be written into the generated script header".to_string(),
            "Name the model <name>.mapping.yaml, using letters, digits, `_`, `-` and `.`, with no leading dot.",
        ));
    }
    findings
}

fn check_header(header: &MappingHeader, findings: &mut Vec<Diagnostic>) {
    for (member, path) in [
        ("targetSchema", &header.target_schema),
        ("script", &header.script),
    ] {
        if !clean_project_artifact_path(path) {
            findings.push(finding(
                MappingCode::PathInvalid,
                format!("/mapping/{member}"),
                format!("mapping.{member} is not a clean relative path"),
                "Use a relative path with no leading slash, no `..` segment, no backslash, and no colon.",
            ));
        }
    }
    if clean_project_artifact_path(&header.script) {
        if !header.script.ends_with(SCRIPT_FILE_SUFFIX) {
            findings.push(finding(
                MappingCode::PathInvalid,
                "/mapping/script".to_string(),
                format!("mapping.script must end with {SCRIPT_FILE_SUFFIX}"),
                "Name the generated script with a .rhai extension.",
            ));
        }
        if header.script == header.target_schema {
            findings.push(finding(
                MappingCode::PathInvalid,
                "/mapping/script".to_string(),
                "mapping.script is the same file as mapping.targetSchema".to_string(),
                "Point the script at its own new path.",
            ));
        }
    }
    if let Some(reason) = entrypoint_fault(&header.entrypoint, header.target) {
        findings.push(finding(
            MappingCode::EntrypointInvalid,
            "/mapping/entrypoint".to_string(),
            format!("mapping.entrypoint is refused: {reason}"),
            "Name a Rhai identifier that does not start with `mapping_`.",
        ));
    }
    let ingestion = header.target == MappingTarget::Ingestion;
    if ingestion && header.ingestion_mode.is_none() {
        findings.push(finding(
            MappingCode::IngestionMode,
            "/mapping/ingestionMode".to_string(),
            "an ingestion mapping must declare mapping.ingestionMode".to_string(),
            "Set ingestionMode to proposal or immediate.",
        ));
    } else if !ingestion && header.ingestion_mode.is_some() {
        findings.push(finding(
            MappingCode::IngestionMode,
            "/mapping/ingestionMode".to_string(),
            "mapping.ingestionMode applies only to the ingestion target".to_string(),
            "Remove ingestionMode, or set mapping.target to ingestion.",
        ));
    }
}

/// Check one assignment; returns its parsed target path when the target
/// text is inside the grammar.
fn check_assignment(
    index: usize,
    assignment: &Assignment,
    schema: &Value,
    schema_file: &str,
    root_ok: bool,
    findings: &mut Vec<Diagnostic>,
) -> Option<Vec<String>> {
    let at = |member: &str| {
        if member.is_empty() {
            format!("/assignments/{index}")
        } else {
            format!("/assignments/{index}/{member}")
        }
    };

    match (&assignment.from, &assignment.constant) {
        (None, None) => findings.push(finding(
            MappingCode::AssignmentInvalid,
            at(""),
            "an assignment needs either from or constant".to_string(),
            "Add a from selector or a constant.",
        )),
        (Some(_), Some(_)) => findings.push(finding(
            MappingCode::AssignmentInvalid,
            at(""),
            "an assignment takes from or constant, not both".to_string(),
            "Remove one of them.",
        )),
        _ => {}
    }
    if assignment.constant.is_some() {
        if assignment.convert != Conversion::None {
            findings.push(finding(
                MappingCode::AssignmentInvalid,
                at("convert"),
                "convert does not apply to a constant".to_string(),
                "Remove convert, or write the constant in the target's type.",
            ));
        }
        if assignment.when_missing != WhenMissing::Fail {
            findings.push(finding(
                MappingCode::AssignmentInvalid,
                at("whenMissing"),
                "whenMissing does not apply to a constant".to_string(),
                "Remove whenMissing.",
            ));
        }
        if let Some(MappingConstant::Text(text)) = &assignment.constant {
            if let Some(reason) = constant_text_fault(text) {
                findings.push(finding(
                    MappingCode::AssignmentInvalid,
                    at("constant"),
                    format!("the constant is refused: {reason}"),
                    "Use shorter text without control characters.",
                ));
            }
        }
    }

    if let Some(selector) = &assignment.from {
        if let Err(error) = parse_selector(selector) {
            findings.push(finding(
                MappingCode::SelectorInvalid,
                at("from"),
                format!("the selector is outside the grammar: {}", error.describe()),
                "Use dotted names or \"quoted\" keys, with optional [key = \"value\"] filters.",
            ));
        }
    }

    let target = match parse_target_path(&assignment.target) {
        Ok(path) => path,
        Err(error) => {
            findings.push(finding(
                MappingCode::TargetInvalid,
                at("target"),
                format!(
                    "the target path is outside the grammar: {}",
                    error.describe()
                ),
                "Use dotted names or \"quoted\" keys; a target path carries no filter.",
            ));
            return None;
        }
    };

    if root_ok {
        check_against_schema(index, assignment, &target, schema, schema_file, findings);
    }
    Some(target)
}

fn check_against_schema(
    index: usize,
    assignment: &Assignment,
    target: &[String],
    schema: &Value,
    schema_file: &str,
    findings: &mut Vec<Diagnostic>,
) {
    let at = |member: &str| format!("/assignments/{index}/{member}");
    let leaf = match resolve_target(schema, target) {
        Resolution::Leaf(leaf) => leaf,
        Resolution::Unknown => {
            findings.push(finding(
                MappingCode::TargetUnknown,
                at("target"),
                format!(
                    "the target path {} names no property of the target schema {schema_file}",
                    assignment.target
                ),
                "Check the path against the schema's properties.",
            ));
            return;
        }
        Resolution::Unsupported(reason) => {
            findings.push(finding(
                MappingCode::SchemaUnsupported,
                at("target"),
                format!("the target schema is outside the supported subset: {reason}"),
                "Use objects with properties and scalar leaves on every mapped path.",
            ));
            return;
        }
        Resolution::NotALeaf => {
            findings.push(finding(
                MappingCode::TargetInvalid,
                at("target"),
                "the target path names an object, not a scalar property".to_string(),
                "Assign each scalar property below the object.",
            ));
            return;
        }
    };
    let leaf_types = type_names(leaf);

    let needed: Option<&[&str]> = match assignment.convert {
        Conversion::None => None,
        Conversion::Integer => Some(&["integer", "number"]),
        Conversion::Text | Conversion::Date => Some(&["string"]),
    };
    if let Some(needed) = needed {
        let fits = leaf_types
            .as_ref()
            .is_some_and(|types| types.iter().any(|name| needed.contains(name)));
        if !fits {
            findings.push(finding(
                MappingCode::ConversionTargetMismatch,
                at("convert"),
                format!(
                    "this conversion needs a target of type {}",
                    needed.join(" or ")
                ),
                "Change the conversion, or the target schema's type.",
            ));
        }
    }
    if let Some(constant) = &assignment.constant {
        let (kind, accepted, value): (&str, &[&str], Value) = match constant {
            MappingConstant::Boolean(value) => ("boolean", &["boolean"], Value::from(*value)),
            MappingConstant::Integer(value) => {
                ("integer", &["integer", "number"], Value::from(*value))
            }
            MappingConstant::Text(value) => ("string", &["string"], Value::from(value.as_str())),
        };
        let type_fits = leaf_types
            .as_ref()
            .is_none_or(|types| types.iter().any(|name| accepted.contains(name)));
        let enum_fits = leaf
            .get("enum")
            .and_then(Value::as_array)
            .is_none_or(|values| values.iter().any(|member| json_equal(member, &value)));
        let const_fits = leaf
            .get("const")
            .is_none_or(|member| json_equal(member, &value));
        if !type_fits {
            findings.push(finding(
                MappingCode::ConversionTargetMismatch,
                at("constant"),
                format!("the constant is {kind} but the target does not accept that type"),
                "Write the constant in the target's type.",
            ));
        } else if !enum_fits || !const_fits {
            findings.push(finding(
                MappingCode::ConversionTargetMismatch,
                at("constant"),
                "the constant is not one of the values the target schema allows".to_string(),
                "Use a value from the schema's enum or const.",
            ));
        }
    }

    if assignment.when_missing == WhenMissing::Omit && is_required_path(schema, target) {
        findings.push(finding(
            MappingCode::OmitRequired,
            at("whenMissing"),
            "whenMissing omit is not allowed for a required target property".to_string(),
            "Use fail, or make the property optional in the schema.",
        ));
    }
}

/// Whether the last segment of `target` is required by its parent object.
fn is_required_path(schema: &Value, target: &[String]) -> bool {
    let Some((last, parents)) = target.split_last() else {
        return false;
    };
    let mut node = schema;
    for name in parents {
        match properties_of(node).and_then(|properties| properties.get(name)) {
            Some(child) => node = child,
            None => return false,
        }
    }
    required_of(node).contains(&last.as_str())
}

fn check_conflicts(parsed: &[Option<Vec<String>>], findings: &mut Vec<Diagnostic>) {
    for (index, target) in parsed.iter().enumerate() {
        let Some(target) = target else { continue };
        let earlier = parsed[..index].iter().position(|other| {
            other
                .as_ref()
                .is_some_and(|other| is_prefix_of(other, target) || is_prefix_of(target, other))
        });
        if let Some(earlier) = earlier {
            findings.push(finding(
                MappingCode::TargetConflict,
                format!("/assignments/{index}/target"),
                format!(
                    "this target is the same as, or contains or lies inside, the target of \
                     /assignments/{earlier}"
                ),
                "Assign each target property once.",
            ));
        }
    }
}

fn check_required(
    node: &Value,
    prefix: &mut Vec<String>,
    targets: &[&[String]],
    findings: &mut Vec<Diagnostic>,
) {
    for name in required_of(node) {
        prefix.push(name.to_string());
        if properties_of(node).is_some_and(|properties| !properties.contains_key(name)) {
            findings.push(finding(
                MappingCode::SchemaUnsupported,
                "/mapping/targetSchema".to_string(),
                format!(
                    "the target schema requires {} but does not declare it in properties",
                    render_path(prefix)
                ),
                "Declare the property in the schema, or remove it from the required list.",
            ));
            prefix.pop();
            continue;
        }
        let exact = targets.iter().any(|target| **target == **prefix);
        let below = targets
            .iter()
            .any(|target| target.len() > prefix.len() && is_prefix_of(prefix, target));
        if !exact && !below {
            findings.push(finding(
                MappingCode::RequiredUnmapped,
                "/assignments".to_string(),
                format!(
                    "the required target property {} has no assignment at or below it",
                    render_path(prefix)
                ),
                "Add an assignment for it, or remove it from the schema's required list.",
            ));
        }
        prefix.pop();
    }
    // Every object on a mapped path answers for its own required members.
    let Some(properties) = properties_of(node) else {
        return;
    };
    for (name, child) in properties {
        if properties_of(child).is_none() {
            continue;
        }
        prefix.push(name.clone());
        let below = targets
            .iter()
            .any(|target| target.len() > prefix.len() && is_prefix_of(prefix, target));
        if below {
            check_required(child, prefix, targets, findings);
        }
        prefix.pop();
    }
}

