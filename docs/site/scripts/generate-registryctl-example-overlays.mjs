import { createHash } from 'node:crypto';
import { mkdir, readdir, readFile, writeFile } from 'node:fs/promises';
import { basename, dirname, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const siteRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const repoRoot = resolve(siteRoot, '../..');
const starterRoot = resolve(
  repoRoot,
  'crates/registryctl/assets/project-starters/bounded-http',
);
const overlays = [
  {
    sourceRoot: resolve(
      repoRoot,
      'crates/registryctl/tests/fixtures/project-authoring/opencrvs-events-api',
    ),
    outputPath: resolve(
      siteRoot,
      'public/examples/registryctl/opencrvs-events-api-overlay-v1.sh',
    ),
    success:
      'Applied the synthetic OpenCRVS Events API-shaped OAuth and Rhai overlay.',
  },
  {
    sourceRoot: resolve(siteRoot, 'examples/registryctl/jsonplaceholder-todo-live'),
    outputPath: resolve(
      siteRoot,
      'public/examples/registryctl/jsonplaceholder-todo-live-overlay-v1.sh',
    ),
    success:
      'Applied the optional no-credential public JSON source demonstration overlay.',
  },
];

async function filesUnder(directory) {
  const entries = await readdir(directory, { withFileTypes: true });
  const paths = [];
  for (const entry of entries.sort((left, right) => left.name.localeCompare(right.name))) {
    const path = resolve(directory, entry.name);
    if (entry.isDirectory()) {
      paths.push(...(await filesUnder(path)));
    } else if (entry.isFile()) {
      paths.push(path);
    }
  }
  return paths;
}

function heredocMarker(path, content) {
  const stem = path.toUpperCase().replaceAll(/[^A-Z0-9]+/g, '_');
  const marker = `REGISTRYCTL_${stem}_EOF`;
  if (content.includes(marker)) {
    throw new Error(`overlay source contains its generated heredoc marker: ${path}`);
  }
  return marker;
}

function sha256(content) {
  return createHash('sha256').update(content).digest('hex');
}

const starterFiles = await filesUnder(starterRoot);
const starterClosure = Object.fromEntries(
  await Promise.all(
    starterFiles.map(async (path) => [
      relative(starterRoot, path),
      sha256(await readFile(path)),
    ]),
  ),
);

for (const overlay of overlays) {
  const sourceFiles = (await filesUnder(overlay.sourceRoot)).filter(
    (path) => relative(overlay.sourceRoot, path) !== 'README.md',
  );
  const outputName = basename(overlay.outputPath);
  const chunks = [
    '#!/bin/sh',
    '# Generated by docs/site/scripts/generate-registryctl-example-overlays.mjs.',
    '# Apply only to the pristine HTTP starter embedded in the matching Registryctl release.',
    'set -eu',
    '',
    'if ! command -v python3 >/dev/null 2>&1; then',
    "  printf '%s\\n' 'python3 is required to verify the HTTP starter closure' >&2",
    '  exit 1',
    'fi',
    '',
    "python3 - <<'REGISTRYCTL_STARTER_VALIDATION_PY'",
    'import hashlib',
    'from pathlib import Path',
    '',
    `expected = ${JSON.stringify(starterClosure, null, 2)}`,
    'ignored_roots = {".registry-stack-editor", ".vscode", ".zed"}',
    `transport_files = {${JSON.stringify(outputName)}, ${JSON.stringify(`${outputName}.sha256`)}}`,
    'root = Path.cwd()',
    '',
    'for name in ignored_roots:',
    '    path = root / name',
    '    if path.exists() and (path.is_symlink() or not path.is_dir()):',
    '        raise SystemExit(f"HTTP starter editor path is not a real directory: {name}")',
    'for name in transport_files:',
    '    path = root / name',
    '    if path.exists() and (path.is_symlink() or not path.is_file()):',
    '        raise SystemExit(f"overlay transport path is not a regular file: {name}")',
    '',
    'actual = {}',
    'for path in root.rglob("*"):',
    '    relative = path.relative_to(root).as_posix()',
    '    if relative.split("/", 1)[0] in ignored_roots or relative in transport_files:',
    '        continue',
    '    if path.is_symlink():',
    '        raise SystemExit(f"HTTP starter closure contains a symbolic link: {relative}")',
    '    if path.is_file():',
    '        actual[relative] = hashlib.sha256(path.read_bytes()).hexdigest()',
    '    elif not path.is_dir():',
    '        raise SystemExit(f"HTTP starter closure contains a non-file entry: {relative}")',
    '',
    'missing = sorted(set(expected) - set(actual))',
    'unexpected = sorted(set(actual) - set(expected))',
    'changed = sorted(path for path in expected.keys() & actual.keys() if expected[path] != actual[path])',
    'if missing or unexpected or changed:',
    '    details = []',
    '    if missing:',
    '        details.append("missing=" + ",".join(missing))',
    '    if unexpected:',
    '        details.append("unexpected=" + ",".join(unexpected))',
    '    if changed:',
    '        details.append("changed=" + ",".join(changed))',
    '    raise SystemExit("HTTP starter closure does not match this release: " + "; ".join(details))',
    'REGISTRYCTL_STARTER_VALIDATION_PY',
    '',
    'rm -r integrations/person-record',
    '',
  ];

  for (const sourcePath of sourceFiles) {
    const path = relative(overlay.sourceRoot, sourcePath);
    const content = await readFile(sourcePath, 'utf8');
    const marker = heredocMarker(path, content);
    chunks.push(`mkdir -p '${dirname(path)}'`);
    chunks.push(`cat >'${path}' <<'${marker}'`);
    chunks.push(content.trimEnd());
    chunks.push(marker);
    chunks.push('');
  }

  chunks.push(`printf '%s\\n' '${overlay.success}'`, '');

  const content = chunks.join('\n');
  await mkdir(dirname(overlay.outputPath), { recursive: true });
  await writeFile(overlay.outputPath, content, {
    encoding: 'utf8',
    mode: 0o644,
  });
  await writeFile(
    `${overlay.outputPath}.sha256`,
    `${sha256(content)}  ${outputName}\n`,
    {
      encoding: 'utf8',
      mode: 0o644,
    },
  );
}
