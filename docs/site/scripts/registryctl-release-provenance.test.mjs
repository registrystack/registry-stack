import assert from 'node:assert/strict';
import { execFile as execFileCallback } from 'node:child_process';
import { readFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { test } from 'node:test';
import { promisify } from 'node:util';

import YAML from 'yaml';

const siteRoot = resolve(import.meta.dirname, '..');
const repositoryRoot = resolve(siteRoot, '../..');
const execFile = promisify(execFileCallback);

async function readSite(relative) {
  return readFile(resolve(siteRoot, relative), 'utf8');
}

test('v0.15 release-form docs stay distinct from published v0.13 and current-source evidence', async () => {
  const [docsetsSource, generatedDocsetsSource, registryctl, configuration, tutorial, releaseSource] =
    await Promise.all([
      readSite('src/data/docsets.yaml'),
      readSite('src/data/generated/docsets.json'),
      readSite('src/content/docs/reference/registryctl.mdx'),
      readSite('src/content/docs/reference/project-configuration.mdx'),
      readSite('src/content/docs/tutorials/author-registry-project.mdx'),
      execFile('git', ['show', 'v0.13.0:crates/registryctl/src/main.rs'], {
        cwd: repositoryRoot,
        maxBuffer: 4 * 1024 * 1024,
      }).then(({ stdout }) => stdout),
    ]);
  const docsets = YAML.parse(docsetsSource);
  const generatedDocsets = JSON.parse(generatedDocsetsSource);
  assert.deepEqual(generatedDocsets, docsets, 'generated docset truth must match its source');

  const current = docsets.docsets.find((docset) => docset.id === docsets.current);
  const lastRelease = docsets.docsets.find((docset) => docset.id === 'v0.13.0');
  assert.equal(current.label, 'Documentation preview');
  assert.equal(current.availability, 'unreleased');
  assert.equal(lastRelease.availability, 'released');

  const registryctlLead = registryctl.split('## Registry Stack project authoring')[0];
  assert.match(registryctlLead, /This page describes `registryctl 0\.14\.0`/);
  assert.match(registryctlLead, /binary, installer, image[\s\n]+lock, and verification material from that same release/);
  assert.doesNotMatch(registryctlLead, /Main source \(unreleased\)/);
  assert.doesNotMatch(
    registryctl,
    /The released command tree comes from the registryctl source at `v0\.13\.0`/,
  );
  assert.doesNotMatch(registryctl, /The command tables on this page come from Main source/);

  assert.match(configuration, /Generated by: Main source \(unreleased\)/);
  assert.match(configuration, /Published release containing this generator: none/);
  assert.match(configuration, /Field release history: not verified/);
  assert.match(configuration, /Compared releases: none/);
  assert.match(configuration, /`history_status: not_verified`/);
  assert.match(configuration, /`introduced_in: null`/);
  assert.doesNotMatch(configuration, /Field availability baseline/);
  assert.doesNotMatch(configuration, /field baseline records when/);
  assert.doesNotMatch(configuration, /Configuration release: `0\.13\.0`/);

  assert.match(tutorial, /uses Registryctl 0\.14\.0 and its matching release material/);
  assert.doesNotMatch(tutorial, /Main source \(unreleased\)/);
  assert.doesNotMatch(tutorial, /v0\.13\.0/);
  const releaseCommands = releaseSource
    .split('enum Commands {')[1]
    .split('#[derive(Debug, Args)]')[0];
  for (const command of [
    'Preflight',
    'Capabilities',
    'Compare',
    'Promote',
    'Migrate',
    'ProjectDiagnostics',
  ]) {
    assert.doesNotMatch(
      releaseCommands,
      new RegExp(`\\b${command}\\b`),
      `${command} must remain absent from the v0.13.0 command tree`,
    );
  }
  const releaseAuthoring = releaseSource
    .split('enum AuthoringCommand {')[1]
    .split('#[derive(Debug, Parser)]')[0];
  assert.doesNotMatch(releaseAuthoring, /\bReference\b/);
  assert.match(tutorial, /Starter: http \(Registry Stack 0\.14\.0\)/);
  for (const page of [registryctl, tutorial]) {
    assert.match(page, /--show-authored-values/);
    assert.match(page, /human(?:-only| output only)/i);
    assert.match(
      page,
      /Secret values, secret references and runtime secret-file locators, fixture data, raw parser text,\s+defaulted values, and derived values remain hidden/,
    );
    assert.match(page, /not a\s+report, evidence, or export mode/);
  }
  assert.match(registryctl, /Default human output,[\s\S]*JSON output,[\s\S]*remain redacted/);
  assert.match(tutorial, /combining[\s\S]*with JSON output is rejected/);
});
