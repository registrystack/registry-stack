class GeneratedGateTests(unittest.TestCase):
    def test_comparator_rejects_a_missing_committed_artifact(self) -> None:
        baseline = SCRIPT_DIR.parent / "generated/minimal"
        with tempfile.TemporaryDirectory() as temporary:
            candidate = Path(temporary) / "candidate"
            shutil.copytree(baseline, candidate)
            (candidate / COMPARATOR.MINIMAL_PATHS[-1]).unlink()
            errors = COMPARATOR.compare(baseline, candidate)
        self.assertTrue(any("candidate is missing expected artifacts" in error for error in errors), errors)

    def test_comparator_requires_native_action_and_proposal_artifacts(self) -> None:
        baseline = SCRIPT_DIR.parent / "generated/facility"
        required = (
            "compiled/actions.json",
            "generated/action-schemas/register-facility.invoke.input.schema.json",
            "generated/action-schemas/register-facility.invoke.response.schema.json",
            "generated/action-schemas/correct-address.invoke.response.schema.json",
            "generated/review-context-schemas/correct-address.schema.json",
            "generated/review-context-schemas/index.json",
        )
        for artifact in required:
            with self.subTest(artifact=artifact), tempfile.TemporaryDirectory() as temporary:
                candidate = Path(temporary) / "candidate"
                shutil.copytree(baseline, candidate)
                (candidate / artifact).unlink()
                errors = COMPARATOR.compare(baseline, candidate)
                self.assertTrue(any(artifact in error for error in errors), errors)
        response = json.loads((baseline / required[3]).read_text())
        self.assertTrue({"actionId", "submissionVersion", "state", "links"} <= response["properties"].keys())
        self.assertEqual(["draft", "submitted", "applied", "cancelled"], response["properties"]["state"]["enum"])

    def test_action_contract_exports_are_required_and_compared_byte_for_byte(self) -> None:
        baseline = SCRIPT_DIR.parent / "generated/facility"
        export = json.loads((baseline / "generated/action-contracts.json").read_text())
        self.assertEqual("BRegActionContracts", export["kind"])
        self.assertEqual("id.registrystack.org/formats/breg/action-contracts/v1", export["apiVersion"])
        for artifact in ("generated/action-contracts.json", "generated/action-contracts.schema.json"):
            with self.subTest(artifact=artifact), tempfile.TemporaryDirectory() as temporary:
                candidate = Path(temporary) / "candidate"
                shutil.copytree(baseline, candidate)
                path = candidate / artifact
                original = path.read_bytes()
                path.unlink()
                errors = COMPARATOR.compare(baseline, candidate)
                self.assertTrue(any(artifact in error and "missing expected artifacts" in error for error in errors), errors)
                path.write_bytes(original + b"\n")
                self.assertIn(f"generated bytes differ: {artifact}", COMPARATOR.compare(baseline, candidate))

    def test_comparator_rejects_unknown_baselines(self) -> None:
        baseline = SCRIPT_DIR.parent / "generated/minimal"
        with tempfile.TemporaryDirectory() as temporary:
            unknown = Path(temporary) / "unregistered"
            shutil.copytree(baseline, unknown)
            with self.assertRaisesRegex(ValueError, "unknown generated baseline"):
                COMPARATOR.compare(unknown, baseline)

    def test_comparator_rejects_unexpected_artifacts_and_changed_bytes(self) -> None:
        baseline = SCRIPT_DIR.parent / "generated/minimal"
        with tempfile.TemporaryDirectory() as temporary:
            candidate = Path(temporary) / "candidate"
            shutil.copytree(baseline, candidate)
            (candidate / "obsolete.schema.json").write_text("{}")
            artifact = "generated/sdk/project.py"
            with (candidate / artifact).open("a") as output:
                output.write("\n# stale SDK\n")
            errors = COMPARATOR.compare(baseline, candidate)
            self.assertTrue(any("candidate has unexpected artifacts: obsolete.schema.json" in error for error in errors), errors)
            self.assertIn(f"generated bytes differ: {artifact}", errors)

    def test_comparator_rejects_a_missing_artifact_in_both_trees(self) -> None:
        baseline = SCRIPT_DIR.parent / "generated/minimal"
        with tempfile.TemporaryDirectory() as temporary:
            incomplete = Path(temporary) / "minimal"
            candidate = Path(temporary) / "candidate"
            shutil.copytree(baseline, incomplete)
            artifact = "generated/postgres/schema.sql"
            (incomplete / artifact).unlink()
            shutil.copytree(incomplete, candidate)
            errors = COMPARATOR.compare(incomplete, candidate)
            self.assertTrue(any(f"baseline is missing expected artifacts: {artifact}" in error for error in errors), errors)
            self.assertTrue(any(f"candidate is missing expected artifacts: {artifact}" in error for error in errors), errors)

